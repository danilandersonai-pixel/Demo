// ============================================================================
// «Поджигатель» — претендент по мотивам главы XII трактата («Огневое нападение»)
// ----------------------------------------------------------------------------
// ПРИНЦИП. «Огонь пускают, когда время сухое и ветер попутный». База — смиренный
// кооператор: сотрудничает, за случайный (шумовой) удар по мирному противнику
// накладывает на себя епитимью и молча принимает до двух ответных ударов, чтобы
// не раздувать эхо-войны. Поверх базы — механика поджога: стратегия постоянно
// измеряет, НАКАЗЫВАЮТСЯ ли её фактические D (шумовые, разведывательные, боевые).
// Если противник систематически не отвечает на удары — «трава сухая» — начинаются
// поджоги: одиночные D с паузами, при устойчивой безнаказанности всё чаще, вплоть
// до сплошного огня. Первый же серьёзный отпор (два наказанных удара подряд или
// половина последних) — мгновенный отбой, извинение и долгий запрет на огонь.
//
// ФИЛОСОФИЯ. Предавать не «когда хочется», а когда обстоятельства открылись:
// безответная жертва (эксплуатация безнаказанна), уже идущая война (доля чужих D
// в окне >= 55% — оборона, изредка оливковая ветвь), выгодное окно великодушия
// (одиночные удары, которые противник прощает). Против «мстителей», карающих
// сериями (два удара за один), включается терпение: одиночные чужие D прощаются
// полностью — воевать с осадой дороже, чем стерпеть шум.
//
// СИЛЬНЫЕ СТОРОНЫ: устойчив к шуму 5% (епитимья гасит эхо, самоигра держится у
// взаимной кооперации); выжимает максимум из беззубых и излишне великодушных;
// не проваливается против агрессоров (военное положение).
// СЛАБЫЕ СТОРОНЫ: разведывательные поджоги стоят пары очков против строгих
// зеркал; великодушие (15%) и оливковые ветви понемногу дарят очки хищникам;
// осторожный отбой оставляет часть прибыли недожатой.
// ПРОТИВ КОГО: доорматы и всепрощающие — сгорают; зеркала и каратели — с ними
// честный мир; вечные предатели — глухая оборона.
// ============================================================================

export default {
  id: 'ch-fire',
  name: 'Поджигатель',
  epithet: 'Огонь по сухой траве',
  color: '#ff6b35',
  dossier: {
    quote: 'Огонь пускают, когда время сухое и ветер попутный: нападай не когда хочешь, а когда обстоятельства открылись.',
    principle: 'Смиренный кооператор с епитимьёй за случайные удары; следит, наказывают ли его D, и жжёт лишь безответных — одиночными, потом чаще; при первом отпоре гасит огонь и извиняется.',
    strengths: [
      'Не разваливается от шума: епитимья обрывает эхо-войны, селф-матч у взаимной кооперации',
      'Распознаёт и дожимает безответных и излишне великодушных, наращивая огонь постепенно',
    ],
    weaknesses: [
      'Разведывательные поджоги и великодушие дарят пару очков строгим зеркалам и хищникам',
      'Осторожный отбой (кулдаун после отпора) оставляет часть эксплуатации недожатой',
    ],
    targets: 'Против доорматов и всепрощающих — эксплуатация; с зеркалами и карателями — мир; против вечных предателей — оборона.',
  },
  create(rng) {
    var lastIntended = null;   // мой задуманный ход прошлого раунда
    var penanceLeft = 0;       // сколько ответных ударов приму молча
    var penanceUntil = -1;     // индекс раунда, до которого действует епитимья
    var probeWindow = [];      // исходы моих фактических D: true = наказан ответным D
    var unpunishedStreak = 0;  // подряд ненаказанных моих D
    var fireActive = false;    // идёт ли поджог
    var fireGap = 2;           // сколько мирных раундов между поджогами
    var sinceMyD = 99;         // раундов с моего последнего фактического D
    var fireCooldownUntil = -1;// до какого раунда огонь запрещён после отпора
    var scoutsLeft = 2;        // лимит разведывательных поджогов
    var avenger = false;       // противник карает сериями (2 удара за 1)

    function tally(arr) {
      var k = 0;
      for (var i = 0; i < arr.length; i++) if (arr[i]) k++;
      return k;
    }

    return {
      move: function (mine, theirs) {
        var n = mine.length;
        if (n === 0) {
          lastIntended = 'C';
          return 'C';
        }

        var myPrev = mine[n - 1];
        var oppPrev = theirs[n - 1];

        // --- учёт прошлого раунда -------------------------------------------
        if (myPrev === 'D') sinceMyD = 0; else sinceMyD++;

        // Мой прошлый фактический D был «несправедливым» (шум на мирном фоне):
        // епитимья — приму до двух ответных ударов, не отвечая.
        if (myPrev === 'D' && lastIntended === 'C' && (n < 2 || theirs[n - 2] === 'C')) {
          penanceLeft = 2;
          penanceUntil = n + 3;
        }

        // Ответ противника на мой D двухраундовой давности: наказан ли поджог?
        if (n >= 2 && mine[n - 2] === 'D') {
          var punished = oppPrev === 'D';
          probeWindow.push(punished);
          if (probeWindow.length > 8) probeWindow.shift();
          if (punished) unpunishedStreak = 0; else unpunishedStreak++;

          if (fireActive) {
            var L = probeWindow.length;
            var twoInARow = L >= 2 && probeWindow[L - 1] && probeWindow[L - 2];
            var halfBurnt = L >= 4 && tally(probeWindow) * 2 >= L;
            if (twoInARow || halfBurnt) {
              // Отпор: гасим огонь, каемся, долгий запрет.
              fireActive = false;
              fireGap = 2;
              fireCooldownUntil = n + 40;
              probeWindow = [];
              unpunishedStreak = 0;
              penanceLeft = 2;
              penanceUntil = n + 3;
            }
          }
        }

        // Мститель: мой одиночный D (на мирном фоне) наказан серией из двух.
        if (!avenger && n >= 3 &&
            mine[n - 3] === 'D' && theirs[n - 3] === 'C' &&
            mine[n - 2] === 'C' && theirs[n - 2] === 'D' &&
            mine[n - 1] === 'C' && theirs[n - 1] === 'D') {
          avenger = true;
        }

        // --- военное положение ----------------------------------------------
        var win = Math.min(15, n);
        var defs = 0;
        for (var i = n - win; i < n; i++) if (theirs[i] === 'D') defs++;
        if (n >= 12 && defs / win >= 0.55) {
          if (rng() < 0.06) { // редкая оливковая ветвь против взаимного тупика
            lastIntended = 'C';
            return 'C';
          }
          lastIntended = 'D';
          return 'D';
        }

        // --- их последний ход — D -------------------------------------------
        if (oppPrev === 'D') {
          if (penanceLeft > 0 && n <= penanceUntil) {
            penanceLeft--;
            lastIntended = 'C';
            return 'C';
          }
          var streak2 = n >= 2 && theirs[n - 2] === 'D';
          if (!streak2) {
            // Одиночный D: против мстителя — полное терпение, иначе великодушие 15%.
            if (avenger || rng() < 0.15) {
              lastIntended = 'C';
              return 'C';
            }
            lastIntended = 'D';
            return 'D';
          }
          // Серия 2+: отвечаю; мстителю — один удар и готовность стерпеть ответ.
          if (avenger) {
            penanceLeft = 2;
            penanceUntil = n + 4;
          }
          lastIntended = 'D';
          return 'D';
        }

        // --- их последний ход — C: мир либо поджог --------------------------
        if (!fireActive && n > fireCooldownUntil && n >= 18) {
          var Lw = probeWindow.length;
          if (Lw >= 3 && tally(probeWindow) / Lw <= 0.34) {
            // Трава сухая, ветер попутный — поджигаем.
            fireActive = true;
            fireGap = 2;
          } else if (Lw < 3 && scoutsLeft > 0 && sinceMyD >= 6 && rng() < 0.25) {
            // Разведывательный поджог: узнать, наказывают ли здесь вообще.
            scoutsLeft--;
            penanceLeft = 2;
            penanceUntil = n + 4;
            lastIntended = 'D';
            return 'D';
          }
        }

        if (fireActive) {
          if (unpunishedStreak >= 12) fireGap = 0;      // сплошной огонь
          else if (unpunishedStreak >= 6) fireGap = 1;  // через раунд
          if (sinceMyD >= fireGap) {
            penanceLeft = 2;                            // если накажут — приму
            penanceUntil = n + 4;
            lastIntended = 'D';
            return 'D';
          }
        }

        lastIntended = 'C';
        return 'C';
      },
    };
  },
};
