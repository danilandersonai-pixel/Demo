'use strict';

/**
 * ДОСЬЕ · «Резонанс» (Resonance)
 *
 * Принцип трактата:
 *   «Тот, кто умеет заставить противника обнаружить форму, а сам формы не имеет,
 *    — сохраняет цельность». (VI. Полнота и пустота)
 *   Резонанс не приносит на поле собственного характера. Он приносит пустой
 *   лист, на котором противник сам вычерчивает свою форму, — и отвечает не
 *   правилом, а расчётом на этой форме.
 *
 * Философия:
 *   Почти вся лига — конечные автоматы с короткой памятью: их следующий ход есть
 *   функция от одного-двух последних раундов. Значит, противника можно не
 *   угадывать, а ИЗМЕРЯТЬ. Резонанс ведёт таблицу переходов «контекст → его
 *   следующий ход», где контекст — пара последних раундов обеих сторон
 *   (мой ход, его ход)×2 = 16 ячеек, поверх которых лежит грубая таблица
 *   глубины 1 из 4 ячеек. Обе таблицы обновляются инкрементально: каждый раунд
 *   в них попадает ровно одно новое наблюдение, история заново не разворачивается.
 *
 *   Оценка вероятности строится иерархически, двумя ступенями сглаживания.
 *   Ячейка глубины 1 сглаживается к «априорной взаимности» (мир отвечает тем же,
 *   чем ты ходил: после моего C ждём C, после моего D — расплату). Ячейка
 *   глубины 2 сглаживается к своей родительской ячейке глубины 1. Поэтому
 *   глубокий контекст начинает говорить своим голосом только тогда, когда
 *   накопит собственную статистику, а редкие наблюдения при 5% шума не
 *   принимаются за закономерность: одно-два искажения тонут в псевдосчётчиках.
 *
 *   ЛОВУШКА И КАК ОНА ОБОЙДЕНА. Наивный «лучший ответ на предсказание» всегда
 *   даёт D — предательство доминирует в одном раунде, и предсказатель
 *   вырождается в «Палача». Резонанс считает не раунд, а КУРС. Пара «мой
 *   последний ход, его последний ход» — это состояние марковского процесса, в
 *   котором мой ход выбирает, в какое состояние мы попадём завтра. По 16
 *   состояниям крутится итерация ценности с дисконтом 0.95 и учётом того, что
 *   мой собственный приказ с вероятностью 5% исполняется наоборот. Ценность —
 *   это «сколько я буду получать за раунд, если продолжу так себя вести».
 *   Взаимное C держит 3 за раунд бесконечно (60 единиц ценности), взаимное D —
 *   1 за раунд (20). Разовая нажива в 5 против «Зеркала» окупается ровно одним
 *   раундом и проваливает курс, и расчёт это видит сам, без единого правила
 *   «будь добрым».
 *
 *   Сверх расчёта стоит порог осторожности: предать разрешено, только если
 *   перевес курса D над курсом C превышает margin = 0.25 + 1.9·(1 − уверенность)
 *   + 0.45·энтропия предсказания. При пустой статистике margin выше любой
 *   мыслимой наживы, поэтому по умолчанию Резонанс сотрудничает; при
 *   предсказании «монетка» (энтропия 1) порог поднимается, чтобы шум не читался
 *   как слабость противника. Стабильные взаимные 3.0 — лучшее, что бывает в
 *   этой игре надолго, и все сомнения трактуются в их пользу.
 *
 *   Отдельная нужда — разведка. Модель никогда не узнает, наказывает ли
 *   противник за предательство, если ни разу не предать. Поэтому у Резонанса
 *   есть жёсткий бюджет из шести пробных D: они тратятся только на видимо
 *   мирного противника, только пока ветка «его ответ на мой D» почти пуста,
 *   и не чаще чем раз в три раунда. Против безответного «Пацифиста» шесть проб
 *   вскрывают кормушку и дальше идёт чистая эксплуатация; против «Зеркала»
 *   те же шесть проб стоят около одного очка каждая и навсегда закрывают
 *   вопрос — расчёт возвращается к сотрудничеству сам.
 *
 *   Прощение тоже не правило, а следствие. После искажённого шумом D моего
 *   приказа Резонанс оказывается в состоянии «я предал, он сотрудничал»,
 *   предсказывает ответный удар и всё равно ходит C: один раунд по нулю дешевле,
 *   чем цепочка взаимных упрёков ценой в 40 единиц. Так «эхо», которое губит
 *   «Зеркало» при шуме, гасится за один ход.
 *
 * Сильные стороны:
 *   — вскрывает и доит любого, кто не наказывает: против безответных выходит
 *     почти на потолок в 5 за раунд;
 *   — марковский расчёт сам порождает контрицию: одиночная помеха не
 *     разворачивается в войну, кооперация с «Зеркалом» переживает шум;
 *   — против «монетки» и глухих предателей уходит в D по расчёту, а не по
 *     обиде, и не платит за иллюзию исправления;
 *   — предсказатель одинаково хорошо ловит и память-1, и память-2, потому что
 *     переключается между глубинами по накопленной статистике, а не по вере.
 *
 * Слабые стороны:
 *   — первые 10–25 раундов уходят на разведку: против явного эксплуататора это
 *     заведомо потерянные очки, а против «Пацифиста» — недобор наживы;
 *   — противник с памятью глубже двух раундов или со скрытым счётчиком терпения
 *     для модели невидим: он выглядит нестационарным, а Резонанс сочтёт его
 *     шумным и уйдёт в осторожность;
 *   — шесть пробных предательств — реальная цена против злопамятных: тот, кто
 *     не прощает вовсе, обрывает кооперацию уже на первой пробе;
 *   — дисконт 0.95 задаёт горизонт около двадцати раундов; на очень коротких
 *     матчах расчёт систематически переоценивает будущее.
 *
 * Против кого рассчитана:
 *   Против всей популяции коротко-памятных автоматов: доверчивых и щедрых
 *   доит, «Зеркало» и его родню держит в мире, «Палача» и «Хаос» распознаёт за
 *   десяток раундов и перестаёт им платить.
 */

var C = 'C';
var D = 'D';

/* ── Параметры расчёта ─────────────────────────────────────────────────────── */

var GAMMA = 0.95; // дисконт: горизонт «курса» ≈ 20 раундов
var NOISE = 0.05; // известная вероятность искажения собственного приказа

var ALPHA1 = 2.5; // псевдосчётчики: глубина 1 → априорная взаимность
var ALPHA2 = 3.0; // псевдосчётчики: глубина 2 → родительская ячейка глубины 1

var CONF_K = 14; // масштаб «достаточной статистики» для уверенности
var M_BASE = 0.25; // базовый порог осторожности
var M_UNCERT = 1.9; // надбавка за неуверенность
var M_ENTROPY = 0.45; // надбавка за энтропию предсказания

var WARM_SWEEPS = 60; // разовая прогонка итерации ценности на старте
var SWEEPS = 3; // подкачка ценности каждый раунд (V живёт между раундами)

var PROBE_BUDGET = 6; // жёсткий бюджет пробных предательств за матч
var PROBE_CHANCE = 0.22;
var PROBE_MIN_ROUND = 6;
var PROBE_GAP = 3; // не чаще раза в три раунда
var PROBE_SAMPLES = 7; // сколько наблюдений «после моего D» считаем достаточным
var PROBE_COOP_GATE = 0.7; // пробуем только видимо мирного

/* Индекс пары раунда: myBit*2 + oppBit, где C=0, D=1 → CC, CD, DC, DD. */
var REWARD = [3, 0, 5, 1]; // мои очки за пару с тем же индексом

/* Априорная взаимность для контекстов глубины 1: P(он сходит C следующим). */
var PRIOR1 = [0.9, 0.6, 0.2, 0.2];

/** Индекс пары ходов одного раунда. */
function pairIndex(my, opp) {
  return (my === D ? 2 : 0) + (opp === D ? 1 : 0);
}

/** Двоичная энтропия в битах, 0..1. */
function entropy(p) {
  if (p <= 0.000001 || p >= 0.999999) return 0;
  return -(p * Math.log(p) + (1 - p) * Math.log(1 - p)) / Math.LN2;
}

module.exports = {
  id: 'resonance',
  latin: 'Resonance',
  name: 'Резонанс',
  color: '#c4b5fd',
  glyph: '虛',
  family: 'challenger',
  tagline: 'Читает форму противника и отвечает расчётом курса',
  dossier: {
    principle:
      '«Тот, кто умеет заставить противника обнаружить форму, а сам формы не имеет, — сохраняет цельность» — VI. Полнота и пустота',
    philosophy:
      'Строит таблицу переходов «контекст из двух последних раундов → его следующий ход» ' +
      'с иерархическим сглаживанием под 5% шума, а затем считает не выгоду раунда, ' +
      'а установившуюся ценность курса: итерация ценности по 16 состояниям с дисконтом 0.95. ' +
      'Поэтому лучший ответ не вырождается в вечное предательство — взаимные 3.0 стоят ' +
      'дороже разовых 5. Неуверенность и высокая энтропия предсказания поднимают порог ' +
      'осторожности и склоняют выбор к сотрудничеству.',
    strengths: [
      'Вскрывает и доит любого, кто не наказывает за предательство',
      'Расчёт сам порождает прощение: одиночная помеха не превращается в войну'
    ],
    weaknesses: [
      'Первые 10–25 раундов уходят на разведку и шесть пробных предательств',
      'Память глубже двух раундов и скрытые счётчики терпения для модели невидимы'
    ],
    targets: 'Против популяции коротко-памятных автоматов: доверчивых доит, «Зеркало» держит в мире'
  },

  create: function (api) {
    var rnd = api && typeof api.random === 'function' ? api.random : null;

    // Таблица глубины 1: контекст (мой прошлый, его прошлый) → его следующий ход.
    var n1 = [0, 0, 0, 0];
    var c1 = [0, 0, 0, 0];
    // Таблица глубины 2: контекст prevPair*4 + lastPair.
    var n2 = [];
    var c2 = [];
    // Ценность состояний и текущие предсказания.
    var V = [];
    var pred = [];
    var i;
    for (i = 0; i < 16; i++) {
      n2[i] = 0;
      c2[i] = 0;
      pred[i] = 0.5;
      V[i] = 2 / (1 - GAMMA); // нейтральный старт: «по два очка за раунд»
    }

    var ingested = 0; // сколько раундов истории уже свёрнуто в таблицы
    var warmed = false;
    var probesUsed = 0;
    var lastProbe = -99;

    /** Свернуть новые раунды в таблицы. Ровно одно наблюдение за вызов. */
    function ingest(h) {
      var len = h.length;
      while (ingested < len) {
        var t = ingested;
        if (t >= 1) {
          var next = h.opp(t) === D ? 1 : 0;
          var p1 = pairIndex(h.mine(t - 1), h.opp(t - 1));
          n1[p1] += 1;
          if (!next) c1[p1] += 1;
          if (t >= 2) {
            var s = pairIndex(h.mine(t - 2), h.opp(t - 2)) * 4 + p1;
            n2[s] += 1;
            if (!next) c2[s] += 1;
          }
        }
        ingested += 1;
      }
    }

    /** Сглаженная вероятность «он сходит C» для контекста глубины 1. */
    function level1(p1) {
      return (c1[p1] + ALPHA1 * PRIOR1[p1]) / (n1[p1] + ALPHA1);
    }

    /** Пересобрать 16 предсказаний: глубина 2, сглаженная к своему родителю. */
    function refresh() {
      var parent = [level1(0), level1(1), level1(2), level1(3)];
      var s;
      for (s = 0; s < 16; s++) {
        pred[s] = (c2[s] + ALPHA2 * parent[s & 3]) / (n2[s] + ALPHA2);
      }
    }

    /** Ценность курса: сходить xBit из состояния s и дальше играть оптимально. */
    function wValue(s, xBit) {
      var p = pred[s];
      var base = (s & 3) * 4 + xBit * 2;
      return (
        p * (REWARD[xBit * 2] + GAMMA * V[base]) +
        (1 - p) * (REWARD[xBit * 2 + 1] + GAMMA * V[base + 1])
      );
    }

    /** То же с поправкой на то, что мой приказ с вероятностью NOISE исказится. */
    function qValue(s, xBit) {
      return (1 - NOISE) * wValue(s, xBit) + NOISE * wValue(s, 1 - xBit);
    }

    /** Один проход итерации ценности по всем 16 состояниям. */
    function sweep() {
      var s, qc, qd;
      for (s = 0; s < 16; s++) {
        qc = qValue(s, 0);
        qd = qValue(s, 1);
        V[s] = qc > qd ? qc : qd;
      }
    }

    /** Разведка: стоит ли потратить пробное предательство. */
    function shouldProbe(h) {
      if (!rnd) return false;
      if (probesUsed >= PROBE_BUDGET) return false;
      if (h.length < PROBE_MIN_ROUND) return false;
      if (h.length - lastProbe < PROBE_GAP) return false;
      // Ветка «его ответ на мой D» уже наполнена — измерять больше нечего.
      if (n1[2] + n1[3] >= PROBE_SAMPLES) return false;
      if (h.oppCoopRate() < PROBE_COOP_GATE) return false;
      return rnd() < PROBE_CHANCE;
    }

    return {
      move: function (h) {
        ingest(h);
        // Доброе начало: пока нет пары раундов, состояния не существует.
        if (h.length < 2) return C;

        refresh();
        if (!warmed) {
          for (var k = 0; k < WARM_SWEEPS; k++) sweep();
          warmed = true;
        } else {
          for (var j = 0; j < SWEEPS; j++) sweep();
        }

        var s = pairIndex(h.mine(-2), h.opp(-2)) * 4 + pairIndex(h.mine(-1), h.opp(-1));
        var qc = qValue(s, 0);
        var qd = qValue(s, 1);

        // Порог осторожности. Рисковать нечем, когда сотрудничества и не
        // предвиделось: ломать можно только то, что стоит. Поэтому вся надбавка
        // масштабируется предсказанной вероятностью его сотрудничества —
        // против предсказанного предательства защита включается сразу.
        var p = pred[s];
        var neff = n2[s] + 0.5 * n1[s & 3];
        var conf = neff / (neff + CONF_K);
        var margin = p * (M_BASE + M_UNCERT * (1 - conf) + M_ENTROPY * entropy(p));

        var choice = qd - qc > margin ? D : C;

        if (choice === C && shouldProbe(h)) {
          probesUsed += 1;
          lastProbe = h.length;
          choice = D;
        }
        return choice;
      }
    };
  }
};
