// Сидируемый ГПСЧ (mulberry32) и детерминированное комбинирование сидов.
// Никаких Math.random/Date.now в симуляции: вся случайность — отсюда.

/**
 * mulberry32 — быстрый 32-битный ГПСЧ. Один seed → одна и та же
 * последовательность чисел в [0, 1).
 */
function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Детерминированная свёртка двух 32-битных значений в новый сид.
 * Используется, чтобы каждый матч получал независимый поток случайности,
 * не зависящий от порядка матчей в турнире.
 */
function combineSeed(a, b) {
  // a и b входят несимметрично (a перемешивается умножением до подмешивания b),
  // иначе XOR сделал бы свёртку коммутативной: combine(1,2) === combine(2,1).
  let h = (a >>> 0) ^ 0x9e3779b9;
  h = Math.imul(h, 0x85ebca6b) >>> 0;
  h ^= h >>> 13;
  h = Math.imul(h ^ (b >>> 0), 2654435761) >>> 0;
  h ^= h >>> 16;
  return h >>> 0;
}

/** Свёртка произвольного числа компонентов: combineSeedAll(seed, gen, i, j). */
function combineSeedAll(...parts) {
  let h = 0x811c9dc5;
  for (const p of parts) h = combineSeed(h, p);
  return h;
}

// Ядро игры: повторяющаяся дилемма заключённого с шумом.
//
// Матрица выплат:  R=3 (оба C), P=1 (оба D), T=5 (я D, он C), S=0 (я C, он D).
// Шум («дрожащая рука»): с вероятностью noise фактический ход игрока
// становится противоположным задуманному; фактический ход видят оба игрока.


const C = 'C';
const D = 'D';

const PAYOFFS = { R: 3, P: 1, T: 5, S: 0 };

/** Выплата игроку, сыгравшему myMove против oppMove (матрица переопределяема). */
function payoff(myMove, oppMove, P = PAYOFFS) {
  if (myMove === C) return oppMove === C ? P.R : P.S;
  return oppMove === C ? P.T : P.P;
}

function flip(move) {
  return move === C ? D : C;
}

function assertMove(move, strategyId, round) {
  if (move !== C && move !== D) {
    throw new Error(
      `Стратегия «${strategyId}» вернула недопустимый ход ${JSON.stringify(move)} в раунде ${round}`
    );
  }
}

/**
 * Один матч между двумя стратегиями.
 *
 * @param {object} stratA — модуль стратегии ({ id, create })
 * @param {object} stratB — модуль стратегии
 * @param {object} opts
 *   rounds   — число раундов (стратегиям неизвестно), по умолчанию 200
 *   noise    — вероятность искажения хода, по умолчанию 0.05
 *   seed     — сид матча; из него выводятся три независимых потока
 *   rngNoise/rngA/rngB — необязательные переопределения потоков (для тестов)
 *
 * Стратегии видят ТОЛЬКО копии массивов фактических ходов текущего матча.
 */
function playMatch(stratA, stratB, opts = {}) {
  const rounds = opts.rounds ?? 200;
  const noise = opts.noise ?? 0.05;
  const seed = opts.seed ?? 0;
  const P = opts.payoffs ?? PAYOFFS;

  const rngNoise = opts.rngNoise ?? mulberry32(combineSeed(seed, 1));
  const rngA = opts.rngA ?? mulberry32(combineSeed(seed, 2));
  const rngB = opts.rngB ?? mulberry32(combineSeed(seed, 3));

  const playerA = stratA.create(rngA);
  const playerB = stratB.create(rngB);

  const movesA = [];
  const movesB = [];
  let scoreA = 0;
  let scoreB = 0;
  let coopA = 0;
  let coopB = 0;

  for (let r = 0; r < rounds; r++) {
    const intendedA = playerA.move(movesA.slice(), movesB.slice());
    const intendedB = playerB.move(movesB.slice(), movesA.slice());
    assertMove(intendedA, stratA.id, r);
    assertMove(intendedB, stratB.id, r);

    let actualA = intendedA;
    let actualB = intendedB;
    if (noise > 0) {
      if (rngNoise() < noise) actualA = flip(actualA);
      if (rngNoise() < noise) actualB = flip(actualB);
    }

    movesA.push(actualA);
    movesB.push(actualB);
    scoreA += payoff(actualA, actualB, P);
    scoreB += payoff(actualB, actualA, P);
    if (actualA === C) coopA++;
    if (actualB === C) coopB++;
  }

  return {
    rounds,
    scoreA,
    scoreB,
    avgA: scoreA / rounds,
    avgB: scoreB / rounds,
    coopA: coopA / rounds,
    coopB: coopB / rounds,
    movesA,
    movesB,
  };
}

  return { mulberry32, combineSeed, combineSeedAll, C, D, PAYOFFS, payoff, playMatch };
