function describeFile(fileName) {
  var name = String(fileName || '').split(/[\\/]/).pop();
  var lower = name.toLowerCase();
  if (BY_NAME[lower]) return BY_NAME[lower];
  // составные расширения (.test.js) — раньше простых
  var m = lower.match(/(\.[a-z0-9]+\.[a-z0-9]+)$/);
  if (m && BY_EXT[m[1]]) return BY_EXT[m[1]];
  m = lower.match(/(\.[a-z0-9]+)$/);
  if (m && BY_EXT[m[1]]) return BY_EXT[m[1]];
  if (lower.indexOf('.') === -1) return 'Файл без расширения — чаще всего служебный или текстовый.';
  return 'Файл проекта. По расширению «' + (m ? m[1] : '?') + '» «Штурман» его пока не знает.';
}

module.exports = { describeFile: describeFile, BY_NAME: BY_NAME, BY_EXT: BY_EXT };
