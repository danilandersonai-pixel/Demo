// ДОСЬЕ ────────────────────────────────────────────────────────────────
// «Полководец» (Patience) — авторская, направление «Терпение».
// Принцип из трактата (по мотивам гл. XI): «Вначале будь как невинная
// дева — и враг откроет дверь. Потом будь как вырвавшийся заяц — и враг
// не успеет защититься».
// Философия: кампания имеет фазы, и поза воина должна меняться с фазой.
//  • Разведка (раунды 0–39): осторожное Зеркало — изучай, не подставляйся.
//  • Кампания (40–139): великодушие — одиночные предательства (почти
//    наверняка шум) прощаются, наказываются только серии из двух и более.
//    Это фаза сбора урожая: чинить кооперацию дешевле, чем воевать.
//  • Осада (140+): терпение кончилось — за любое D следуют два ответных
//    удара. Поздние предательства недопустимы, репутация уже не нужна,
//    нужна дисциплина.
// Полностью детерминирован: ни одного обращения к ГПСЧ.
// Сильные стороны: в середине матча неуязвим для шума (лучше Зеркала);
// в конце неуязвим для поздних хищников (лучше великодушных).
// Слабые стороны: в осаде сам страдает от шума — случайное D врага
// раскручивает двойное возмездие; против Агрессора фаза великодушия
// доплачивает.
// Против кого рассчитан: против шума в середине и против жадных
// «концовщиков» в финале.
// ──────────────────────────────────────────────────────────────────────

import { C, D } from '../engine/game.js';

const CAMPAIGN_FROM = 40; // начало фазы великодушия
const SIEGE_FROM = 140; // начало фазы строгости

export default {
  id: 'patience',
  name: 'Полководец',
  epithet: 'дева вначале, заяц в конце',
  color: '#b9c344',
  dossier: {
    quote: 'Вначале будь как невинная дева — потом как вырвавшийся заяц.',
    principle: 'Три фазы: осторожное Зеркало (0–39), великодушие к одиночным сбоям (40–139), двойное возмездие за всё (140+).',
    strengths: ['В середине матча шум ему не страшен: одиночные D прощены', 'В финале не даёт себя доить поздним хищникам', 'Детерминирован: поведение точно предсказуемо и тестируемо'],
    weaknesses: ['В осаде чужой случайный сбой раскручивает двойную кару', 'Великодушная фаза доплачивает вечному агрессору'],
    targets: 'Против шума в середине партии и жадных «концовщиков» в её финале.',
  },
  create() {
    let punishLeft = 0; // остаток двойного возмездия в фазе осады
    return {
      move(mine, theirs) {
        const r = mine.length;
        if (r === 0) return C;
        const oppLast = theirs[r - 1];
        if (r < CAMPAIGN_FROM) {
          // Разведка: чистое Зеркало.
          return oppLast;
        }
        if (r < SIEGE_FROM) {
          // Кампания: наказывать только серии (2+ подряд D).
          if (oppLast === D && r >= 2 && theirs[r - 2] === D) return D;
          return C;
        }
        // Осада: за любое D — два ответных удара.
        if (oppLast === D) punishLeft = 2;
        if (punishLeft > 0) {
          punishLeft--;
          return D;
        }
        return C;
      },
    };
  },
};
