// ─────────────────────────────────────────────────────────────────────────────
// «ПУСТОТА» (ch-void) — претендент по мотивам главы VI трактата Сунь-Цзы,
// «Пустота и полнота».
//
// Принцип. «Появляйся там, где пусто; уклоняйся там, где полно». Стратегия
// непрерывно измеряет, наказывает ли оппонент за предательство. Пока он «полон»
// (мстит, давит) — держит безупречный мир: прощает одиночные D как шум, карает
// только серии 2+, а за собственные случайные (шумовые) или неудачные удары
// приносит покаяние — молча принимает ответный удар, не раскручивая вендетту.
// Изредка, в полной тишине, наносит одиночный зонд-укол и два раунда слушает
// ответ. Наказали — зонд признан ошибкой: покаяние, тройное удлинение паузы,
// снова мир. Не наказали — «пустота» подтверждается; после трёх безнаказанных
// зондов начинается «жатва»: доля предательств растёт ступенями 35% → 65% → 95%,
// но каждый раунд проверяется отпор. Появились серии D или всплеск D у
// оппонента — жатва мгновенно сворачивается с покаянием. Против почти сплошных
// D — война с редкой оливковой ветвью; против частых одиночных D (алернаторы,
// вымогатели) — зеркало без прощения.
//
// Философия. Не воевать с сильным и не спать рядом со слабым: мир — не цель и
// не догма, а цена, которую платят полному; пустота же существует, чтобы её
// занимали. Вся агрессия — строго дозированная разведка боем: каждый удар либо
// подтверждает пустоту, либо оплачивается покаянием.
//
// Сильные стороны: доит непротивящихся (AllC и близких) почти досуха; устойчива
// к шуму 5% (прощение одиночных + покаяние гасят эхо-вендетты); в селф-матче
// зонды взаимно прощаются и счёт держится у кооперативного потолка; против
// карателей (зеркала, «Полководца») быстро выучивает «не трогать» и живёт миром.
//
// Слабые стороны: платит за разведку против мстительных (каждый зонд до вывода
// «полно» стоит очков); ступенчатая жатва раскачивается десятки раундов и не
// успевает добить пустого в коротком матче; редкие шумовые серии у мирного
// оппонента может принять за отпор и на время отступить.
//
// Против кого: в первую очередь — против безусловных и чрезмерно великодушных
// кооператоров; против «Полководца» и прочих карателей — честный мир почти на
// уровне взаимного C.
// ─────────────────────────────────────────────────────────────────────────────

const C = 'C';
const D = 'D';

// Ступени «жатвы»: вероятность D на каждом уровне эксплуатации пустоты.
const HARVEST_D_PROB = [0, 0.35, 0.65, 0.95];

export default {
  id: 'ch-void',
  name: 'Пустота',
  epithet: 'Бьёт туда, где никто не держит строй',
  color: '#8fd3c7',
  dossier: {
    quote: 'Появляйся там, где пусто; уклоняйся там, где полно. Избегай силы — бей по слабости.',
    principle:
      'Одиночные зонды ищут не-наказывающих: пустых доит по нарастающей (35→65→95% D под ежераундным контролем отпора), перед полными держит мир с прощением одиночных D и покаянием за свои.',
    strengths: [
      'Почти досуха выдаивает безусловных кооператоров, не переставая слушать отпор',
      'Прощение одиночных D плюс покаяние за свои гасят шумовые вендетты — селф-матч у кооперативного потолка',
    ],
    weaknesses: [
      'Каждый зонд против мстительного оппонента оплачен очками, пока не выучено «полно»',
      'Жатва раскачивается ступенями и может не успеть добить пустого; шумовую серию может принять за отпор',
    ],
    targets:
      'Безусловные и сверхвеликодушные кооператоры; с карателями уровня «Полководца» — расчётливый мир.',
  },

  create(rng) {
    const intended = []; // мои задуманные (до шума) ходы
    let apology = 0; // сколько чужих ударов принять молча (покаяние)
    let probeRound = -1; // раунд последнего зонда
    let probePending = false; // зонд ждёт оценки (2 раунда наблюдения)
    let cooldown = 10 + Math.floor(rng() * 5); // пауза между зондами
    let nextProbe = 7 + Math.floor(rng() * 6); // раунд, с которого можно зондировать
    let emptyStreak = 0; // подряд безнаказанных зондов
    let harvest = 0; // уровень жатвы 0..3
    let harvestRounds = 0; // чистых раундов на текущем уровне жатвы
    let olive = 8 + Math.floor(rng() * 6); // счётчик до оливковой ветви в войне

    function countD(arr, span) {
      const n = arr.length;
      let k = 0;
      for (let i = Math.max(0, n - span); i < n; i++) if (arr[i] === D) k++;
      return k;
    }

    function hasPairD(arr, span) {
      const n = arr.length;
      for (let i = Math.max(1, n - span + 1); i < n; i++) {
        if (arr[i] === D && arr[i - 1] === D) return true;
      }
      return false;
    }

    function cancelProbe(t) {
      if (probePending) {
        probePending = false;
        nextProbe = t + cooldown;
      }
    }

    function decide(mine, theirs) {
      const t = mine.length;
      if (t === 0) return C;

      // 1. Покаяние за шум: задумал C, вышло D — обидел без умысла.
      if (mine[t - 1] === D && intended[t - 1] === C) {
        apology = Math.min(2, apology + 1);
      }

      // 2. Оценка зонда после двух раундов наблюдения.
      if (probePending && t >= probeRound + 3) {
        probePending = false;
        // Кара приходит немедленно; D через раунд — чаще собственный шум врага.
        const punished = theirs[probeRound + 1] === D;
        if (punished) {
          // «Полно»: признать ошибку, принять кару, надолго затихнуть.
          emptyStreak = 0;
          harvest = 0;
          apology = Math.min(2, apology + 1);
          cooldown = Math.min(500, cooldown * 3 + 4);
        } else {
          // «Пусто»: сокращать паузу, копить уверенность.
          emptyStreak++;
          cooldown = Math.max(6, cooldown - 4);
          if (emptyStreak >= 2 && harvest === 0) {
            harvest = 1;
            harvestRounds = 0;
          }
        }
        nextProbe = t + cooldown;
      }

      const lastTheir = theirs[t - 1];
      const prevTheir = t >= 2 ? theirs[t - 2] : C;
      const d16 = countD(theirs, 16);
      const d20 = countD(theirs, 20);

      // 3. ВОЙНА: враг «полон тьмы» — почти сплошные D.
      if (t >= 16 && d16 >= 9) {
        harvest = 0;
        emptyStreak = 0;
        harvestRounds = 0;
        cancelProbe(t);
        // Их C в осаде драгоценен — немедленно отвечать миром (быстрое перемирие).
        if (lastTheir === C) return C;
        olive--;
        if (olive <= 0) {
          olive = 9 + Math.floor(rng() * 6);
          return C; // оливковая ветвь: выход из взаимной осады
        }
        return D;
      }

      // 4. ЗЕРКАЛО: частые одиночные D (алернаторы, вымогатели) — без прощения.
      if (t >= 20 && d20 >= 6) {
        if (harvest > 0) {
          harvest = 0;
          emptyStreak = 0;
          harvestRounds = 0;
          cooldown = Math.min(500, cooldown * 2 + 4);
        }
        cancelProbe(t);
        if (lastTheir === D) return rng() < 0.1 ? C : D;
        // Явный алернатор (больше половины D) — бить и по его C.
        return d20 >= 11 ? D : C;
      }

      // 5. Жатва: ежераундный контроль отпора.
      if (harvest > 0) {
        const dw = countD(theirs, 12);
        const pair = hasPairD(theirs, 12);
        if ((pair && dw >= 3) || dw >= 6) {
          // Жёсткий отбой: «пустота» оказалась ловушкой.
          harvest = 0;
          emptyStreak = 0;
          harvestRounds = 0;
          apology = Math.min(2, apology + 1);
          cooldown = Math.min(500, cooldown * 3 + 4);
          nextProbe = t + cooldown;
        } else if (dw >= 4) {
          // Мягкий отбой: похоже на шум — снизить уровень, сохранить доверие.
          harvest--;
          harvestRounds = 0;
          if (harvest === 0) {
            emptyStreak = 2;
            nextProbe = t + cooldown;
          }
        } else {
          harvestRounds++;
          if (harvestRounds >= 10 && harvest < 3) {
            harvest++;
            harvestRounds = 0;
          }
        }
      }

      // 6. Мир: покаяние, прощение одиночных, отпор сериям.
      if (lastTheir === D) {
        if (apology > 0) {
          apology--; // принять заслуженный удар молча
          return C;
        }
        if (prevTheir === D) return D; // серия 2+ — отпор
        return C; // одиночный D — прощаем как шум
      }

      // lastTheir === C
      if (harvest > 0) {
        return rng() < HARVEST_D_PROB[harvest] ? D : C;
      }

      // 7. Зонд в полной тишине.
      if (
        !probePending &&
        t >= nextProbe &&
        apology === 0 &&
        lastTheir === C &&
        prevTheir === C &&
        mine[t - 1] === C
      ) {
        probePending = true;
        probeRound = t;
        nextProbe = t + 1000; // до оценки зонда — никаких новых
        return D;
      }

      return C;
    }

    return {
      move(mine, theirs) {
        const m = decide(mine, theirs);
        intended.push(m);
        return m;
      },
    };
  },
};
