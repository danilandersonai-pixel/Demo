  var T = KC.TILE;
  // кольцо болтов на торце: axis — ось фланца ('x' | 'y' | 'z'), sgn — с какой стороны торец (+1 / −1)
  function bolts(g, axis, c, R, n, s, sgn, a0) {
    for (var i = 0; i < n; i++) {
      var a = (a0 || 0) + i / n * Math.PI * 2, ca = Math.cos(a) * R, sa = Math.sin(a) * R, e = s * 0.6 * (sgn || 1);
      if (axis === 'y') g.box(c[0] + ca - s / 2, c[1], c[2] + sa - s / 2, c[0] + ca + s / 2, c[1] + e, c[2] + sa + s / 2, T.rgSteel);
      else if (axis === 'x') g.box(c[0], c[1] + ca - s / 2, c[2] + sa - s / 2, c[0] + e, c[1] + ca + s / 2, c[2] + sa + s / 2, T.rgSteel);
      else g.box(c[0] + ca - s / 2, c[1] + sa - s / 2, c[2], c[0] + ca + s / 2, c[1] + sa + s / 2, c[2] + e, T.rgSteel);
    }
  }
  function fixBox(g, x0, y0, z0, x1, y1, z1, t) {      // коробка с корректным порядком координат
    g.box(Math.min(x0, x1), Math.min(y0, y1), Math.min(z0, z1), Math.max(x0, x1), Math.max(y0, y1), Math.max(z0, z1), t);
  }
  // дуга ленты тормоза вокруг шкива (ось X), от a0 до a1
  function band(g, x0, x1, cy, cz, R, a0, a1) {
    var n = 14, prev = null;
    for (var i = 0; i <= n; i++) {
      var a = a0 + (a1 - a0) * i / n, p = [(x0 + x1) / 2, cy + Math.sin(a) * R, cz + Math.cos(a) * R];
      if (prev) g.beam(prev, p, 0.035, x1 - x0, T.rgDark, { up: [1, 0, 0] });
      prev = p;
    }
  }

