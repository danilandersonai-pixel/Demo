import { C, D } from '../engine/game.js';

export default {
  id: 'random',
  name: 'Хаос',
  epithet: 'монетка вместо плана',
  color: '#b57edc',
  dossier: {
    quote: 'У кого нет плана, того нельзя переиграть по плану.',
    principle: 'Каждый ход — независимая монетка 50/50 из сидированного ГПСЧ.',
    strengths: ['Немоделируем: разведка по его истории бесполезна', 'Изредка больно кусает кооператоров'],
    weaknesses: ['Не удерживает кооперацию и не ведёт войну до конца', 'Провоцирует мстителей и платит за это'],
    targets: 'Контрольная группа: показывает, сколько стоит игра без стратегии.',
  },
  create(rng) {
    return {
      move() {
        return rng() < 0.5 ? C : D;
      },
    };
  },
};
