// ДОСЬЕ ────────────────────────────────────────────────────────────────
// «Притворщик» (Feint) — авторская, направление «Обманчивая слабость».
// Принцип из трактата (по мотивам гл. I): «Война — путь обмана. Если ты
// силён — кажись слабым».
// Философия: пятнадцать раундов он неотличим от Пацифиста. Потом — один
// пробный удар. Три раунда он смотрит, ответят ли ему, продолжая
// кланяться. Если возмездия не последовало — маска сброшена: перед ним
// доверчивый, и его можно доить. Если ответили — Притворщик «извиняется»
// и до конца матча играет честное Зеркало: с сильным он не воюет.
// В режиме эксплуатации сторожевой счётчик: если жертва вдруг начала
// отвечать (больше половины D в последних 10 раундах) — немедленно
// вернуться к честной игре.
// Сильные стороны: против доверчивых — почти Агрессор; против ответчиков
// — почти Зеркало. Дешёвая разведка: один удар вместо постоянных проб.
// Слабые стороны: проба на «Мстителе» — вечная война; при шуме можно
// ошибочно счесть доверчивого мстителем (случайное D в окне наблюдения).
// Против кого рассчитан: против «Пацифиста» и великодушных прощателей.
// ──────────────────────────────────────────────────────────────────────

import { C, D } from '../engine/game.js';

const PROBE_ROUND = 15; // до этого — маска пацифиста
const WATCH_ROUNDS = 3; // окно наблюдения за возмездием
const WAKE_WINDOW = 10; // окно сторожевого счётчика в режиме эксплуатации

export default {
  id: 'feint',
  name: 'Притворщик',
  epithet: 'сильный, кажущийся слабым',
  color: '#ef6da8',
  dossier: {
    quote: 'Война — путь обмана: если ты силён — кажись слабым.',
    principle: 'Пятнадцать раундов маски пацифиста, один пробный удар, три раунда наблюдения: мстят — играть честное Зеркало, не мстят — эксплуатировать.',
    strengths: ['Против доверчивых зарабатывает почти как Агрессор', 'Против ответчиков теряет всего один раунд и живёт как Зеркало', 'Сторожевой счётчик замечает «проснувшуюся» жертву'],
    weaknesses: ['Проба на Мстителе — вечная война', 'Шум в окне наблюдения может выдать доверчивого за мстителя'],
    targets: 'Против Пацифиста, Хаоса и великодушных прощателей.',
  },
  create() {
    let mode = 'mask'; // mask → watch → exploit | citizen
    return {
      move(mine, theirs) {
        const r = mine.length;
        if (mode === 'mask') {
          if (r < PROBE_ROUND) return C;
          mode = 'watch';
          return D; // пробный удар
        }
        if (mode === 'watch') {
          const sinceProbe = r - (PROBE_ROUND + 1);
          if (sinceProbe < WATCH_ROUNDS) return C; // кланяюсь и смотрю
          // Вердикт: было ли возмездие в окне после пробы?
          let retaliations = 0;
          for (let t = PROBE_ROUND + 1; t < PROBE_ROUND + 1 + WATCH_ROUNDS; t++) {
            if (theirs[t] === D) retaliations++;
          }
          mode = retaliations > 0 ? 'citizen' : 'exploit';
        }
        if (mode === 'exploit') {
          // Сторожевой счётчик: жертва проснулась?
          let recentD = 0;
          const from = Math.max(0, r - WAKE_WINDOW);
          for (let t = from; t < r; t++) {
            if (theirs[t] === D) recentD++;
          }
          if (recentD * 2 > Math.min(WAKE_WINDOW, r - from)) {
            mode = 'citizen';
          } else {
            return D;
          }
        }
        // citizen: честное Зеркало до конца матча.
        if (r === 0) return C;
        return theirs[r - 1];
      },
    };
  },
};
