const OPENING_ROUNDS = 12; // разведфаза: TFT + два пробных удара
const PROBE_ROUNDS = [5, 8]; // «разведка боем»

window.ARENA_LEAGUE.register( {
  id: 'scout',
  name: 'Лазутчик',
  epithet: 'знай врага и знай себя',
  color: '#d4af37',
  dossier: {
    quote: 'Знай врага и знай себя — и в ста сражениях не будешь знать поражения.',
    principle: 'Разведфаза с пробными ударами, затем модель оппонента P(C|моё C), P(C|моё D) и лучший ответ: мир, если мир доходнее войны.',
    strengths: ['Эксплуатирует безответных почти как Агрессор', 'С ответчиками сохраняет мир и полные 3.0', 'Переоценивает модель каждый раунд — адаптируется к смене режима'],
    weaknesses: ['Пробные удары фатальны против Мстителя', 'Первые 12 раундов уязвим: модель ещё пуста'],
    targets: 'Против всех сразу: не стиль, а лучший ответ каждому конкретному врагу.',
  },
  create() {
    return {
      move(mine, theirs) {
        const r = mine.length;
        if (r < OPENING_ROUNDS) {
          if (PROBE_ROUNDS.includes(r)) return D;
          return r === 0 ? C : theirs[r - 1]; // TFT в разведфазе
        }
        // Модель: ответ оппонента в раунде t на мой ход в раунде t-1.
        let nAfterC = 0;
        let cAfterC = 0;
        let nAfterD = 0;
        let cAfterD = 0;
        for (let t = 1; t < r; t++) {
          if (mine[t - 1] === C) {
            nAfterC++;
            if (theirs[t] === C) cAfterC++;
          } else {
            nAfterD++;
            if (theirs[t] === C) cAfterD++;
          }
        }
        // Сглаживание Лапласа: не делаем крайних выводов из пары наблюдений.
        const pCifC = (cAfterC + 1) / (nAfterC + 2);
        const pCifD = (cAfterD + 1) / (nAfterD + 2);
        // Долгосрочная ожидаемая выплата за раунд: мир против войны.
        const evPeace = 3 * pCifC;
        const evWar = 5 * pCifD + 1 * (1 - pCifD);
        return evPeace >= evWar ? C : D;
      },
    };
  },
});

