// ─────────────────────────────────────────────────────────────────────────────
// «ПУСТОТА» (ch-void) — претендент по мотивам главы VI трактата Сунь-Цзы,
// «Пустота и полнота».
//
// Принцип. «Появляйся там, где пусто; уклоняйся там, где полно». Стратегия
// непрерывно измеряет, наказывает ли оппонент за предательство. Пока он «полон»
// (мстит, давит) — держит безупречный мир: прощает одиночные D как шум, карает
// только серии 2+, а за собственные случайные (шумовые) или неудачные удары
// приносит покаяние — молча принимает ответный удар, не раскручивая вендетту.
// Изредка, в полной тишине, наносит одиночный зонд-укол и слушает ответ.
// Наказали — зонд признан ошибкой: покаяние, тройное удлинение паузы, снова
// мир. Не наказали — «пустота» подтверждается; после двух безнаказанных зондов
// начинается «жатва»: доля предательств растёт ступенями 35% → 65% → 95%, но
// каждый раунд проверяется отпор. Появились серии D или всплеск D у оппонента —
// жатва мгновенно сворачивается с покаянием. Против почти сплошных D — война с
// оливковой ветвью; против частых одиночных D — зеркало без прощения.
//
// КРУГ 2 — что изменено и почему (по логам круга 1: 5-е место из 5, все матчи
// 2.7–2.8 — «нигде не провалилась, нигде не выиграла», поле сплошь каратели,
// зонды стоили дороже, чем приносили, селф-матч 2.80 против ≥2.9 у лидеров):
//   1. РОДОВОЙ ЗНАК. Ход D строго в раунде 2 — опознавательный знак. Если и у
//      оппонента в раунде 2 стоит D, а остальные первые ходы — почти чистые C
//      (допуск в один шумовой сбой), он признаётся роднёй: никаких зондов и
//      жатвы, только мирное ядро с прощением и покаянием. Селф-матч поднимается
//      к шумовому потолку (~2.95), а Пацифист/Дипломат/зеркала знак не
//      воспроизводят (эхо-D у зеркал приходит в раунд 3, не во 2-й) и роднёй не
//      прикинутся. При всплеске D родство отзывается.
//   2. ЛИМИТ РАЗВЕДКИ. Два наказанных зонда за матч — и разведка закрыта
//      навсегда: против карателей (Мститель, Зеркало, Полководец в осаде)
//      больше не платим за уже известный ответ «полно». Безнаказанные зонды
//      по-прежнему сокращают паузу — пустоту доим как раньше.
//   3. ДЕТЕКТОР ХАОСА. Если оппонент бьёт часто (≥32% D за матч), а его ответ
//      на мои D не отличается от фона (некоррелирован — Хаос, алернатор,
//      Агрессор, сорвавшийся навеки Мститель), включается чистое D без
//      оливковых ветвей: перед бессмысленной силой не заискивать, а собирать
//      максимум. Отпускает, только если оппонент устойчиво вернулся к C.
//
// Философия. Не воевать с сильным и не спать рядом со слабым: мир — не догма,
// а цена, которую платят полному; пустота же существует, чтобы её занимали.
// Родню — беречь, карателей — не трогать, хаос — стричь, пустых — доить.
//
// Сильные стороны: селф-матч у шумового потолка (родовой знак); доит
// непротивящихся почти досуха; с карателями после двух уроков живёт чистым
// миром; хаос и вечных мстителей стрижёт чистым D.
// Слабые стороны: родовой знак стоит одного эха против зеркальных карателей;
// разведка до вывода «полно» оплачена очками; шумовую серию мирного оппонента
// может принять за отпор и на время отступить.
// Против кого: безусловные и сверхвеликодушные кооператоры, хаотики и
// сломавшиеся мстители; с карателями уровня «Полководца» — расчётливый мир.
// ─────────────────────────────────────────────────────────────────────────────

const C = 'C';
const D = 'D';

// Ступени «жатвы»: вероятность D на каждом уровне эксплуатации пустоты.
const HARVEST_D_PROB = [0, 0.35, 0.65, 0.95];

export default {
  id: 'ch-void',
  name: 'Пустота',
  epithet: 'Бьёт туда, где никто не держит строй',
  color: '#8fd3c7',
  dossier: {
    quote: 'Появляйся там, где пусто; уклоняйся там, где полно. Избегай силы — бей по слабости.',
    principle:
      'Одиночные зонды ищут не-наказывающих: пустых доит по нарастающей (35→65→95% D под ежераундным контролем отпора), перед полными держит мир с прощением одиночных D и покаянием за свои.',
    round2:
      'Родовой знак (D строго в раунде 2 при чистых C вокруг) опознаёт родню — с ней ни зондов, ни жатвы, селф-матч у шумового потолка. Разведка ограничена: два наказанных зонда за матч — и больше никогда, карателям не переплачиваем. Детектор хаоса: частые D без корреляции с моими ходами (Хаос, Агрессор, сорвавшийся Мститель) — чистое D без оливковых ветвей, пока оппонент устойчиво не вернётся к C.',
    strengths: [
      'Селф-матч у шумового потолка благодаря родовому знаку; непротивящихся доит почти досуха',
      'С карателями после двух уроков — чистый мир; хаос и вечных мстителей стрижёт чистым D',
    ],
    weaknesses: [
      'Родовой знак стоит одного эха против зеркальных карателей; разведка до вывода «полно» оплачена очками',
      'Шумовую серию мирного оппонента может принять за отпор и на время отступить от жатвы',
    ],
    targets:
      'Безусловные и сверхвеликодушные кооператоры, хаотики, сломавшиеся мстители; с карателями уровня «Полководца» — расчётливый мир.',
  },

  create(rng) {
    const intended = []; // мои задуманные (до шума) ходы
    let apology = 0; // сколько чужих ударов принять молча (покаяние)
    let probeRound = -1; // раунд последнего зонда
    let probePending = false; // зонд ждёт оценки
    let punishedProbes = 0; // наказанных зондов за матч (2 — разведка закрыта)
    let cooldown = 10 + Math.floor(rng() * 5); // пауза между зондами
    let nextProbe = 7 + Math.floor(rng() * 6); // раунд, с которого можно зондировать
    let emptyStreak = 0; // подряд безнаказанных зондов
    let harvest = 0; // уровень жатвы 0..3
    let harvestRounds = 0; // чистых раундов на текущем уровне жатвы
    let olive = 8 + Math.floor(rng() * 6); // счётчик до оливковой ветви в войне
    let twin = false; // опознана родня (родовой знак)
    let kin = false; // родня опознавалась хоть раз — детектор хаоса закрыт навсегда
    let twinChecked = false;
    let chaosLock = false; // оппонент — некоррелированный хаос: чистое D
    let lockAge = 0; // сколько раундов держится chaosLock
    let chainOn = false; // идёт цепочка перемирия внутри chaosLock
    let chainStrikes = 0; // прощённые одиночные D внутри цепочки

    function countD(arr, span) {
      const n = arr.length;
      let k = 0;
      for (let i = Math.max(0, n - span); i < n; i++) if (arr[i] === D) k++;
      return k;
    }

    function hasPairD(arr, span) {
      const n = arr.length;
      for (let i = Math.max(1, n - span + 1); i < n; i++) {
        if (arr[i] === D && arr[i - 1] === D) return true;
      }
      return false;
    }

    function cancelProbe(t) {
      if (probePending) {
        probePending = false;
        nextProbe = t + cooldown;
      }
    }

    function decide(mine, theirs) {
      const t = mine.length;
      if (t === 0) return C;

      // 1. Покаяние за шум: задумал C, вышло D — обидел без умысла.
      if (mine[t - 1] === D && intended[t - 1] === C) {
        apology = Math.min(2, apology + 1);
      }

      // 2. Оценка зонда после двух раундов наблюдения.
      if (probePending && t >= probeRound + 3) {
        probePending = false;
        // Кара приходит немедленно; D через раунд — чаще собственный шум врага.
        const punished = theirs[probeRound + 1] === D;
        if (punished) {
          // «Полно»: признать ошибку, принять кару, надолго затихнуть.
          punishedProbes++;
          emptyStreak = 0;
          harvest = 0;
          apology = Math.min(2, apology + 1);
          cooldown = Math.min(500, cooldown * 3 + 4);
        } else {
          // «Пусто»: сокращать паузу, копить уверенность.
          emptyStreak++;
          cooldown = Math.max(6, cooldown - 4);
          if (emptyStreak >= 2 && harvest === 0) {
            harvest = 1;
            harvestRounds = 0;
          }
        }
        nextProbe = t + cooldown;
      }

      // 3. Родовой знак: D строго в раунде 2.
      if (t === 2) return D;

      // 4. Опознание родни по их первым пяти ходам.
      if (!twinChecked && t >= 5) {
        twinChecked = true;
        if (theirs[2] === D) {
          let mm = 0;
          if (theirs[0] !== C) mm++;
          if (theirs[1] !== C) mm++;
          if (theirs[3] !== C) mm++;
          if (theirs[4] !== C) mm++;
          if (mm <= 1) {
            twin = true;
            kin = true; // на родню детектор хаоса не наводим даже после ссоры
          }
        }
      }

      const lastTheir = theirs[t - 1];
      const prevTheir = t >= 2 ? theirs[t - 2] : C;
      const d16 = countD(theirs, 16);
      const d20 = countD(theirs, 20);

      // 5. Детектор хаоса (не для родни): частые D, причём ответ оппонента не
      // зависит от моих ходов — D после моего C так же вероятен, как после
      // моего D. Зеркала и каратели так не выглядят: у них D после моего D
      // резко чаще, чем после моего C. На родню (даже после ссоры) не наводим.
      if (!twin && !kin) {
        if (!chaosLock && t >= 25 && d20 >= 7) {
          const from = Math.max(0, t - 60);
          let myD = 0;
          let myC = 0;
          let afterD = 0;
          let afterC = 0;
          let theirTot = 0;
          let span = 0;
          for (let k = from; k + 1 < t; k++) {
            span++;
            if (theirs[k + 1] === D) theirTot++;
            if (mine[k] === D) {
              myD++;
              if (theirs[k + 1] === D) afterD++;
            } else {
              myC++;
              if (theirs[k + 1] === D) afterC++;
            }
          }
          if (myD >= 8 && myC >= 5 && span > 0) {
            const base = theirTot / span;
            const respD = afterD / myD;
            const respC = afterC / myC;
            if (base >= 0.32 && respD - respC <= 0.15) {
              chaosLock = true;
            }
          }
        }
        if (chaosLock) {
          // Отпускает, только если оппонент устойчиво вернулся к миру.
          if (20 - d20 >= 15) {
            chaosLock = false;
            lockAge = 0;
            chainOn = false;
          } else {
            harvest = 0;
            emptyStreak = 0;
            cancelProbe(t);
            lockAge++;
            // Цепочка перемирия: страховка от вечного клинча двух «Пустот»,
            // не узнавших друг друга из-за шума в родовом знаке. Обе копии
            // делят номер раунда, поэтому синхронно пробуют мир в окне t%37.
            if (chainOn) {
              if (lastTheir === D) {
                if (prevTheir === D) {
                  chainOn = false; // серия — это не перемирие
                  return D;
                }
                chainStrikes++; // одиночные D прощаем как шум, но считаем
                if (chainStrikes >= 3) {
                  chainOn = false; // трёх одиночных хватит (алернатор!)
                  return D;
                }
                return C;
              }
              return C;
            }
            if (lockAge >= 25 && t % 37 === 0) {
              chainOn = true;
              chainStrikes = 0;
              return C; // синхронная оливковая ветвь
            }
            if (lastTheir === C && mine[t - 1] === C) {
              chainOn = true;
              chainStrikes = 0;
              return C; // взаимный C — подхватить перемирие
            }
            return D; // стричь хаос
          }
        }
      }

      // 6. ВОЙНА: враг «полон тьмы» — почти сплошные D (но отвечает на ходы).
      if (t >= 16 && d16 >= 9) {
        harvest = 0;
        emptyStreak = 0;
        harvestRounds = 0;
        cancelProbe(t);
        // Их C в осаде драгоценен — немедленно отвечать миром (перемирие).
        if (lastTheir === C) return C;
        olive--;
        if (olive <= 0) {
          olive = 9 + Math.floor(rng() * 6);
          return C; // оливковая ветвь: выход из взаимной осады
        }
        return D;
      }

      // 7. ЗЕРКАЛО: частые одиночные D — без прощения. Для родни порог выше
      // (шумовые ссоры не повод), но всплеск отзывает родство.
      const mirrorGate = twin ? 8 : 6;
      if (t >= 20 && d20 >= mirrorGate) {
        twin = false; // родня так себя не ведёт
        if (harvest > 0) {
          harvest = 0;
          emptyStreak = 0;
          harvestRounds = 0;
          cooldown = Math.min(500, cooldown * 2 + 4);
        }
        cancelProbe(t);
        if (lastTheir === D) return rng() < 0.1 ? C : D;
        // Явный алернатор (больше половины D) — бить и по его C.
        return d20 >= 11 ? D : C;
      }

      // 8. Жатва: ежераундный контроль отпора.
      if (harvest > 0) {
        const dw = countD(theirs, 12);
        const pair = hasPairD(theirs, 12);
        if ((pair && dw >= 3) || dw >= 6) {
          // Жёсткий отбой: «пустота» оказалась ловушкой.
          harvest = 0;
          emptyStreak = 0;
          harvestRounds = 0;
          apology = Math.min(2, apology + 1);
          cooldown = Math.min(500, cooldown * 3 + 4);
          nextProbe = t + cooldown;
        } else if (dw >= 4) {
          // Мягкий отбой: похоже на шум — снизить уровень, сохранить доверие.
          harvest--;
          harvestRounds = 0;
          if (harvest === 0) {
            emptyStreak = 2;
            nextProbe = t + cooldown;
          }
        } else {
          harvestRounds++;
          if (harvestRounds >= 10 && harvest < 3) {
            harvest++;
            harvestRounds = 0;
          }
        }
      }

      // 9. Мир: покаяние, прощение одиночных, отпор сериям.
      if (lastTheir === D) {
        if (apology > 0) {
          apology--; // принять заслуженный удар молча
          return C;
        }
        if (prevTheir === D) return D; // серия 2+ — отпор
        return C; // одиночный D — прощаем как шум
      }

      // lastTheir === C
      if (harvest > 0) {
        return rng() < HARVEST_D_PROB[harvest] ? D : C;
      }

      // 10. Зонд в полной тишине — родню не зондируем, после двух уроков
      // разведка закрыта навсегда.
      if (
        !twin &&
        punishedProbes < 2 &&
        !probePending &&
        t >= nextProbe &&
        apology === 0 &&
        lastTheir === C &&
        prevTheir === C &&
        mine[t - 1] === C
      ) {
        probePending = true;
        probeRound = t;
        nextProbe = t + 1000; // до оценки зонда — никаких новых
        return D;
      }

      return C;
    }

    return {
      move(mine, theirs) {
        const m = decide(mine, theirs);
        intended.push(m);
        return m;
      },
    };
  },
};
