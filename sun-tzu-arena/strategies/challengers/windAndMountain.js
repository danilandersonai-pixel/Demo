'use strict';

/**
 * ДОСЬЕ · «Ветер и Гора» (WindAndMountain)
 *
 * Принцип трактата:
 *   «Двигайся быстрый, как ветер; будь спокойный и медлительный, как лес;
 *    при нападении и грабеже будь подобен огню; будь неподвижен, как гора».
 *   (VII. Борьба на войне) — знамённый девиз фуринкадзан: 風林火山.
 *   Сунь-цзы не предлагает выбрать одну из четырёх повадок. Он требует уметь
 *   все четыре и знать, когда какая уместна. Полководец, у которого есть только
 *   быстрота, проигрывает терпеливому; у которого только неподвижность — тому,
 *   кто ушёл вперёд.
 *
 * Философия:
 *   Стратегия — это конечный автомат из четырёх ЯВНЫХ режимов. Никакой смеси,
 *   никаких вероятностных дозировок: в каждый момент действует ровно одна
 *   повадка, и переход между ними происходит только при выполнении измеримого
 *   условия на статистике истории.
 *
 *     ВЕТЕР  (風) — отражение последнего хода соперника. Режим непрочитанного
 *                   противника: реагировать мгновенно, пока не понял, кто перед
 *                   тобой. Дополнен «повинностью»: если мой собственный приказ
 *                   сорвался (вернул C, а в историю ушло D — это видно по
 *                   сравнению move() с h.mine(-1)), я не отвечаю на его законную
 *                   месть, а держу C до двух раундов, пока он не успокоится.
 *                   Так гасится эхо, которое губит обычное Зеркало при шуме.
 *     ЛЕС    (林) — ровное безусловное сотрудничество. Ни одного зонда: зонд
 *                   стоит раунд, а лес молчит. Осечки собственного приказа лес
 *                   гасит сам собой — он и так играет C, поэтому месть партнёра
 *                   не превращается в цепочку.
 *     ОГОНЬ  (火) — безусловное предательство против того, кто ДОКАЗАЛ, что не
 *                   отвечает на удар. Доказательство даётся бесплатно: шум сам
 *                   срывает ~5% моих приказов на D, и h.oppCoopAfter('D')
 *                   показывает, чем он на это ответил. Зонд не нужен — ветер
 *                   приносит пробу сам.
 *     ГОРА   (山) — безусловное предательство против того, с кем сотрудничество
 *                   невозможно. Ни зондов, ни попыток примирения, ни реакции на
 *                   провокации. Единственный необратимый режим: гора не сходит
 *                   с места.
 *
 *   ПОЛНАЯ ТАБЛИЦА ПЕРЕХОДОВ (n = h.length, D%(k) = доля предательств соперника
 *   за последние k раундов; всё, что ниже, реализовано в коде буквально):
 *
 *   ┌── из ───┬── условие ─────────────────────────────────────────┬── в ────┐
 *   │ ВЕТЕР   │ n ≥ 20 и D%(20) ≥ 0.70                             │ ГОРА    │
 *   │         │   (безусловный предатель — говорить не о чем)       │         │
 *   │ ВЕТЕР   │ n ≥ 30, D%(30) ≥ 0.40, наблюдений его отклика на    │ ГОРА    │
 *   │         │ мой C ≥ 10 и oppCoopAfter('C') ≤ 0.62               │         │
 *   │         │   (предаёт постоянно и не отвечает на мою руку)      │         │
 *   │ ВЕТЕР   │ n ≥ 25, огонь не заблокирован, наблюдений его       │ ОГОНЬ   │
 *   │         │ отклика на мой D ≥ 2, oppCoopAfter('D') ≥ 0.70,     │         │
 *   │         │ D%(25) ≤ 0.15  (не мстит и вообще почти не предаёт)  │         │
 *   │ ВЕТЕР   │ n ≥ 10 и D%(20) ≤ 0.18                             │ ЛЕС     │
 *   │         │   (0.18 — потолок чистого шума: 5% его осечек плюс   │         │
 *   │         │    5% ответов на мои, с запасом на разброс)          │         │
 *   │ ЛЕС     │ в Лесу ≥ 8 раундов и D%(15) ≥ 0.40                 │ ВЕТЕР   │
 *   │         │   (быстрый выход: кто-то доит тишину)                │         │
 *   │ ЛЕС     │ в Лесу ≥ 20 раундов и доля его D за весь Лес ≥ 0.25 │ ВЕТЕР   │
 *   │         │   (медленный выход: тихая подтравка ниже порога 0.40)│         │
 *   │ ЛЕС     │ те же условия, что ВЕТЕР → ОГОНЬ                    │ ОГОНЬ   │
 *   │ ЛЕС     │ те же условия, что ВЕТЕР → ГОРА                    │ ГОРА    │
 *   │ ОГОНЬ   │ в Огне ≥ 8 раундов и доля его D за Огонь ≥ 0.35     │ ВЕТЕР   │
 *   │         │   (он ответил на удар — Огонь был ошибкой: включаю   │         │
 *   │         │    повинность и НАВСЕГДА запрещаю себе Огонь)        │         │
 *   │ ГОРА    │ — никогда —                                         │ —       │
 *   └─────────┴─────────────────────────────────────────────────────┴─────────┘
 *
 *   Две поправки на шум, без которых автомат сходит с ума:
 *   1) ни один порог не стоит вблизи 5%: наказание начинается там, где шум уже
 *      не объяснение (0.40 за окно, 0.25 за длинный отрезок, 0.35 в Огне);
 *   2) выход из Огня считается по НАКОПЛЕННОЙ доле с момента входа, а не по
 *      короткому окну, — иначе доверчивого соперника «выведет из Огня» пара
 *      случайных помех, и 4.7 за раунд превратятся в 3.0;
 *   3) 15 раундов после Огня Гора не строится: эхо собственного огня — не
 *      доказательство, что мир невозможен.
 *
 * Сильные стороны:
 *   — четыре чистых ответа вместо одного компромиссного: максимум против
 *     доверчивых (Огонь), минимум потерь против непримиримых (Гора), полный
 *     R против надёжных (Лес);
 *   — повинность в Ветре и безусловное C в Лесу делают её устойчивой к 5% шума
 *     там, где Зеркало и Мститель разваливаются;
 *   — Огонь открывается без единого потраченного зонда — пробу приносит шум;
 *   — ошибка Огня самокорректируется за 8 раундов и больше не повторяется.
 *
 * Слабые стороны:
 *   — Лес — безусловное C: соперник, который держит предательства ниже 0.25,
 *     доит её примерно 20 раундов до срабатывания медленного выхода;
 *   — Гора необратима: противник, который был жесток первые 30 раундов и
 *     исправился на 40-м, потерян навсегда;
 *   — вход в Огонь ждёт двух осечек шума, то есть в среднем ~40 раундов: против
 *     «Овцы» первая пятая часть матча отыграна вежливо и даром.
 *
 * Против кого рассчитана:
 *   Огонь — против «Овцы», «Дара небес» и любого, кто не мстит. Гора — против
 *   «Агрессора» и «Хаоса», с которыми сотрудничество недостижимо. Лес — против
 *   «Зеркала», «Павлова» и собственной копии: там, где партнёр надёжен, любое
 *   шевеление только теряет очки. Ветер — против всех остальных, пока не
 *   прочитаны.
 */

var C = 'C';
var D = 'D';

var WIND = 'wind';
var FOREST = 'forest';
var FIRE = 'fire';
var MOUNTAIN = 'mountain';

/* ===== Пороги. Меняешь здесь — меняй и таблицу в шапке. ===== */

var FOREST_ENTER_MIN = 10; // раундов до первого суждения о надёжности
var FOREST_ENTER_WINDOW = 20;
var FOREST_ENTER_MAX_DEF = 0.18; // потолок «это только шум»

var FOREST_EXIT_MIN = 8; // раундов в Лесу до быстрого выхода
var FOREST_EXIT_WINDOW = 15;
var FOREST_EXIT_DEF = 0.4;
var FOREST_SLOW_MIN = 20; // раундов в Лесу до медленного выхода
var FOREST_SLOW_DEF = 0.25;

var FIRE_ENTER_MIN = 25;
var FIRE_ENTER_WINDOW = 25;
var FIRE_ENTER_MAX_DEF = 0.15;
var FIRE_ENTER_SAMPLES = 2; // наблюдений его отклика на мой D
var FIRE_ENTER_FORGIVE = 0.7; // и он сотрудничал после них

var FIRE_EXIT_MIN = 8; // раундов Огня до проверки
var FIRE_EXIT_DEF = 0.35; // накопленная доля его D за Огонь

var MOUNTAIN_HARD_MIN = 20;
var MOUNTAIN_HARD_WINDOW = 20;
var MOUNTAIN_HARD_DEF = 0.7;
var MOUNTAIN_SOFT_MIN = 30;
var MOUNTAIN_SOFT_WINDOW = 30;
var MOUNTAIN_SOFT_DEF = 0.4;
var MOUNTAIN_SOFT_SAMPLES = 10; // наблюдений его отклика на мой C
var MOUNTAIN_SOFT_RECIPROCITY = 0.62;
var MOUNTAIN_BLOCK_AFTER_FIRE = 15; // раундов запрета Горы после Огня

var APOLOGY_LIMIT = 2; // сколько раундов держать повинность за одну осечку

/** Доля предательств соперника за последние k раундов (0 при пустой истории). */
function oppDefRate(h, k) {
  var arr = h.moves(k).opp;
  if (!arr.length) return 0;
  var d = 0;
  for (var i = 0; i < arr.length; i++) {
    if (arr[i] === D) d++;
  }
  return d / arr.length;
}

module.exports = {
  id: 'windAndMountain',
  latin: 'WindAndMountain',
  name: 'Ветер и Гора',
  color: '#fda4af',
  glyph: '風',
  family: 'challenger',
  tagline: 'Четыре повадки фуринкадзан: ветер, лес, огонь, гора',
  dossier: {
    principle:
      '«Двигайся быстрый, как ветер; будь спокойный, как лес; при нападении будь подобен огню; ' +
      'будь неподвижен, как гора» — VII. Борьба на войне',
    philosophy:
      'Автомат из четырёх явных режимов с измеримыми переходами. ВЕТЕР — отражение последнего хода ' +
      'плюс повинность за собственную осечку, режим непрочитанного соперника. ЛЕС — безусловное C ' +
      'без единого зонда, пока его предательства не выходят за 0.18 шумового потолка. ОГОНЬ — ' +
      'безусловное D против того, кто доказал, что не отвечает на удар (пробу приносит шум, а не ' +
      'зонд); при первом же отпоре Огонь гаснет навсегда. ГОРА — безусловное D против того, с кем ' +
      'мир невозможен: ни зондов, ни примирения, единственный необратимый режим. Все пороги ' +
      'вынесены далеко от 5% шума, а выход из Огня считается по накопленной статистике, не по окну.',
    strengths: [
      'Четыре чистых ответа вместо одного компромиссного: 4.7 против доверчивых, 3.0 против надёжных',
      'Повинность за свою осечку и безусловный Лес гасят эхо, на котором ломаются Зеркало и Мститель'
    ],
    weaknesses: [
      'Лес — безусловное C: подтравка ниже 0.25 доит его до 20 раундов',
      'Гора необратима, а вход в Огонь ждёт двух осечек шума — в среднем ~40 раундов вежливости'
    ],
    targets: 'Огонь — против «Овцы» и не мстящих; Гора — против «Агрессора» и «Хаоса»; Лес — против «Зеркала» и своей копии'
  },
  create: function () {
    var mode = WIND;
    var intent = C; // что я вернул в прошлом раунде (до шума)
    var observed = 0; // до какого раунда разобрана история

    var contrite = false; // мой приказ сорвался — я в долгу
    var apology = 0;

    var forestRounds = 0;
    var forestDefects = 0;

    var fireRounds = 0;
    var fireDefects = 0;
    var fireLocked = false; // он ответил на удар — Огня больше не будет

    var mountainBlockedUntil = 0;

    /** Ветер: отражение последнего хода с поправкой на собственную осечку. */
    function windMove(h) {
      if (h.length === 0) return C;
      if (contrite) {
        if (h.lastOpp() === C) {
          contrite = false;
          apology = 0;
        } else if (apology < APOLOGY_LIMIT) {
          apology++;
          return C;
        } else {
          contrite = false;
          apology = 0;
        }
      }
      return h.lastOpp() === D ? D : C;
    }

    /** Условия входа в Огонь — одни и те же из Ветра и из Леса. */
    function fireReady(h) {
      if (fireLocked) return false;
      if (h.length < FIRE_ENTER_MIN) return false;
      if (h.oppSamplesAfter(D) < FIRE_ENTER_SAMPLES) return false;
      if (h.oppCoopAfter(D, 0) < FIRE_ENTER_FORGIVE) return false;
      return oppDefRate(h, FIRE_ENTER_WINDOW) <= FIRE_ENTER_MAX_DEF;
    }

    /** Условия входа в Гору — одни и те же из Ветра и из Леса. */
    function mountainReady(h) {
      var n = h.length;
      if (n < mountainBlockedUntil) return false;
      if (n >= MOUNTAIN_HARD_MIN && oppDefRate(h, MOUNTAIN_HARD_WINDOW) >= MOUNTAIN_HARD_DEF) {
        return true;
      }
      if (n < MOUNTAIN_SOFT_MIN) return false;
      if (oppDefRate(h, MOUNTAIN_SOFT_WINDOW) < MOUNTAIN_SOFT_DEF) return false;
      if (h.oppSamplesAfter(C) < MOUNTAIN_SOFT_SAMPLES) return false;
      return h.oppCoopAfter(C, 1) <= MOUNTAIN_SOFT_RECIPROCITY;
    }

    function enterForest() {
      mode = FOREST;
      forestRounds = 0;
      forestDefects = 0;
    }

    function enterFire() {
      mode = FIRE;
      fireRounds = 0;
      fireDefects = 0;
      contrite = false;
      apology = 0;
    }

    return {
      move: function (h) {
        var n = h.length;

        /* --- 1. Разбор прошлого раунда: что исполнилось на самом деле --- */
        if (n > 0 && n !== observed) {
          observed = n;
          // Осечка приказа: вернул C, а в историю ушло D. Виден только так.
          if (intent === C && h.mine(-1) === D) {
            contrite = true;
            apology = 0;
          }
          if (mode === FOREST) {
            forestRounds++;
            if (h.opp(-1) === D) forestDefects++;
          } else if (mode === FIRE) {
            fireRounds++;
            if (h.opp(-1) === D) fireDefects++;
          }
        }

        /* --- 2. Переходы (ровно таблица из шапки) --- */
        if (mode === FIRE) {
          if (fireRounds >= FIRE_EXIT_MIN && fireDefects / fireRounds >= FIRE_EXIT_DEF) {
            // Он ответил на удар. Огонь был ошибкой — гасим навсегда и повинимся.
            mode = WIND;
            fireLocked = true;
            contrite = true;
            apology = 0;
            mountainBlockedUntil = n + MOUNTAIN_BLOCK_AFTER_FIRE;
          }
        } else if (mode === WIND) {
          if (mountainReady(h)) {
            mode = MOUNTAIN;
          } else if (fireReady(h)) {
            enterFire();
          } else if (
            n >= FOREST_ENTER_MIN &&
            oppDefRate(h, FOREST_ENTER_WINDOW) <= FOREST_ENTER_MAX_DEF
          ) {
            enterForest();
          }
        } else if (mode === FOREST) {
          if (
            (forestRounds >= FOREST_EXIT_MIN &&
              oppDefRate(h, FOREST_EXIT_WINDOW) >= FOREST_EXIT_DEF) ||
            (forestRounds >= FOREST_SLOW_MIN && forestDefects / forestRounds >= FOREST_SLOW_DEF)
          ) {
            mode = WIND;
          } else if (mountainReady(h)) {
            mode = MOUNTAIN;
          } else if (fireReady(h)) {
            enterFire();
          }
        }
        // MOUNTAIN — выхода нет.

        /* --- 3. Действие режима --- */
        var out;
        if (mode === FOREST) {
          out = C;
        } else if (mode === FIRE || mode === MOUNTAIN) {
          out = D;
        } else {
          out = windMove(h);
        }

        intent = out;
        return out;
      }
    };
  }
};
