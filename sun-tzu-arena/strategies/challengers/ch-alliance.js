// ДОСЬЕ: «Союзник» (ch-alliance)
// ----------------------------------------------------------------------------
// Принцип (глава III, «Стратегическое нападение»): лучшее — разбить замыслы
// врага, затем его союзы, и лишь потом войска. В эволюционном турнире
// выживает не победитель матчей, а тот, чей блок кооперации даёт популяции
// наибольшую среднюю выплату. Эта стратегия — клей такого блока.
//
// Философия: не начинать войну первой; чужой одиночный срыв — вероятно шум,
// но безнаказанным он не остаётся; собственные срывы искупать, принимая
// немедленный ответный удар без мести; серийного агрессора изолировать войной.
//
// КРУГ 2 — что изменено и почему (после дойки Поджигателем 2.36/3.20):
//  1. Закрыт канал дойки. Раньше одиночное D терпелось молча — хищник бил
//     разреженно (каждый 3–4 раунд) и никогда не попадал под триггер «2 подряд».
//     Теперь непрощённое D получает ответ 1-к-1 с адаптивной вероятностью:
//     50% при чистой истории соперника, 70% при EMA срывов > 8%,
//     100% при EMA > 15% или серии из 2+ — доильщик разогревает EMA сам
//     и быстро переходит на полный размен, при котором дойка убыточна.
//  2. Кредит искупления ужесточён: сгорает при первом же C соперника
//     (прощается только НЕМЕДЛЕННАЯ расплата — двойной удар «Полководца»
//     приходит именно так), а при разогретом сопернике (EMA > 20%) не
//     действует вовсе: постоянного агрессора «ответными ударами» не оправдать.
//     Выдаётся кредит безусловно после любого моего фактического D — иначе
//     совпадение шумовых ударов рождало цепочки взаимной мести.
//  3. Разведка боем: две пробные атаки в начале матча + учёт ответов на все
//     мои фактические D. Кто систематически не мстит (безответный пацифист:
//     ≤1 ответа на ≥8 моих ударов при коопрейте ≥88%) — переводится в режим
//     дойки (D ~70%). При первом же отпоре — покаяние: возврат к миру и
//     пожизненный запрет дойки в этом матче.
//  4. Селф-матч сохранён: родич отвечает на пробы ударом (≥50%), поэтому
//     свои почти никогда не квалифицируются как «безответные» (а редкая
//     ошибка гасится покаянием), эхо ударов гасится искуплением за 1–2 раунда.
//
// Механика (сводно):
//  * Мир по умолчанию; возмездие 1-к-1 (максимум один удар в очереди —
//    чтобы не раскармливать спирали против осады «за одно D — два удара»).
//  * «Кредит искупления» (owed=2 после любого моего фактического D):
//    прощаю до двух немедленных ответных ударов; кредит сгорает при первом
//    C соперника и не действует против разогретого агрессора (EMA > 20%).
//  * «Счёт обид» (затухание x0.85/раунд, +1 за непрощённое D): порог 3.4 →
//    тотальная война; в войне редкие зондажи мира (двойное C, ~4.5%/раунд
//    после 12 раундов); выход — только по чужому двойному C; после амнистии
//    счёт стартует с 1.2 (рецидивист изолируется быстрее).
//  * Разведка/дойка: события «мой D → их ответ»; если из ≥8 событий ответных
//    ударов ≤1, а соперник почти всегда мирен (коопрейт ≥88%, EMA ≤ 10%) —
//    режим дойки; отпор (два D подряд или >20% D) → покаяние и запрет.
//
// Сильные стороны:
//  * Лучший селф-матч поля сохранён: шумовые срывы гасятся за 1–2 раунда.
//  * Дойка невыгодна: каждый разреженный удар хищника окупается ответным.
//  * Безответных эксплуатирует сам, не отдавая этот ресурс хищникам.
// Слабые стороны:
//  * Против чистого AllD чуть дороже мгновенного Grim (разгон войны, зондажи).
//  * Редкая (< ~10%) ложная дойка великодушной фазы чемпиона — гасится
//    покаянием при первом же его отпоре.
// Против кого рассчитана: кооперативный блок и «Полководец» во всех фазах;
// хищники-доильщики (Поджигатель, Притворщик), безответные пацифисты.
// ----------------------------------------------------------------------------

export default {
  id: 'ch-alliance',
  name: 'Союзник',
  epithet: 'щит союза',
  color: '#5eead4',
  dossier: {
    quote:
      'Сто побед в ста сражениях — не вершина искусства: вершина — разбить замысел врага, не разрушив мира.',
    principle:
      'Не бьёт первым, но и не спускает: непрощённое D получает ответ 1-к-1 с адаптивной вероятностью (50% к шуму, 100% к разогретому хищнику), свои срывы искупает, серийных агрессоров изолирует войной, а безответных — планомерно доит.',
    strengths: [
      'Лучший селф-матч поля при шуме 5%: эхо срывов гасится искуплением за 1–2 раунда',
      'Дойка невыгодна: разреженные удары хищника окупаются ответными 1-к-1, при разогреве — без щедрости',
      'Переживает все три фазы «Полководца», включая осаду «за одно D — два удара»',
    ],
    weaknesses: [
      'Против чистого AllD чуть дороже мгновенного Grim: разгон войны и зондажи мира стоят очков',
      'Редкая ложная дойка великодушного соперника — гасится покаянием при первом отпоре, но пару раундов стоит',
    ],
    targets:
      'Кооперативный блок и чемпион «Полководец»; хищники-доильщики наказываются 1-к-1, серийные агрессоры — войной, безответные пацифисты — доятся.',
    round2:
      'Круг 2: закрыт канал дойки — вместо терпимости к одиночным D введено возмездие 1-к-1 с адаптивной вероятностью (50% при чистой истории, 70% при EMA срывов > 8%, 100% при EMA > 15% или серии 2+): доильщик сам разогревает EMA и переходит на убыточный для себя полный размен. Кредит искупления сгорает при первом же C соперника и не действует против разогретого агрессора (EMA > 20%) — точечный паразит и AllD больше не прощаются, а шумовые совпадения ударов не рождают цепочек мести. Добавлена разведка боем: две пробные атаки и учёт ответов на мои D; кто систематически не мстит (≤1 ответа из ≥8) — доится (D ~70%) с покаянием и пожизненным запретом дойки при первом отпоре. Селф-матч сохранён: родич отвечает на пробы, свои под дойку не попадают.',
  },

  create(rng) {
    // --- возмездие и искупление ---
    const RETAL_COOL = 0.5; // ответ на одиночное D при чистой истории
    const RETAL_WARM = 0.7; // ответ при EMA срывов > EMA_WARM
    const EMA_A = 0.08; // шаг EMA частоты чужих срывов
    const EMA_WARM = 0.08; // подогретый соперник
    const EMA_HOT = 0.15; // разогретый: ответ всегда
    const EMA_NO_EXCUSE = 0.2; // выше — кредит искупления не действует
    // --- война ---
    const DECAY = 0.85; // затухание счёта обид за раунд
    const WAR_AT = 3.4; // порог тотальной войны
    const EXIT_G = 1.2; // счёт обид после амнистии
    const OLIVE_AFTER = 12; // раундов войны до первых зондажей мира
    const OLIVE_P = 0.045; // вероятность зондажа (двойное C) за раунд войны
    // --- разведка и дойка ---
    const PROBE_P = 0.035; // вероятность пробной атаки за раунд окна
    const PROBE_FROM = 12;
    const PROBE_TO = 70;
    const MAX_PROBES = 2;
    const TEST_MIN_EVENTS = 8; // минимум наблюдений «мой D → их ответ»
    const TEST_MAX_ANSWERED = 1; // максимум ответных ударов для «безответного»
    const COOP_MIN = 0.88; // минимальный общий коопрейт кандидата на дойку
    const MILK_D_P = 0.7; // доля D в режиме дойки
    const REPENT_MIN = 8; // раундов дойки до проверки доли отпора
    const REPENT_RATE = 0.2; // доля их D в дойке, при которой каюсь

    let owed = 0; // сколько немедленных ответных ударов прощу
    let consec = 0; // непрощённые D соперника подряд
    let grievance = 0; // затухающий счёт обид
    let anger = 0; // запланированные ответные удары (0 или 1)
    let emaRate = 0.03; // EMA частоты непрощённых чужих D
    let atWar = false;
    let warRounds = 0;
    let oliveLeft = 0; // сколько ещё C доиграть в зондаже мира
    let watchArmed = false; // следующий их ход — ответ на мой вчерашний D
    let rEvents = 0; // наблюдений «мой D → их ход»
    let rAnswered = 0; // из них ответили ударом
    let theirC = 0; // их C за весь матч
    let probesSent = 0;
    let milking = false; // режим дойки безответного
    let milkBanned = false; // покаялся — дойка запрещена до конца матча
    let milkRounds = 0;
    let milkTheirD = 0;

    return {
      move(mine, theirs) {
        const n = mine.length;
        if (n === 0) return 'C';
        const myLast = mine[n - 1];
        const oppLast = theirs[n - 1];
        if (oppLast === 'C') theirC += 1;

        if (!atWar && !milking) {
          grievance *= DECAY;

          // Разведка: был ли их ход ответом на мой позавчерашний D.
          if (watchArmed) {
            rEvents += 1;
            if (oppLast === 'D') rAnswered += 1;
            watchArmed = false;
          }

          // 1. Их ход: прощён (немедленная расплата за мой D) или записан.
          //    Против разогретого агрессора кредит не действует.
          let wantHit = false;
          if (oppLast === 'D') {
            if (owed > 0 && emaRate <= EMA_NO_EXCUSE) {
              owed -= 1;
              consec = 0;
            } else {
              consec += 1;
              grievance += 1;
              emaRate = emaRate * (1 - EMA_A) + EMA_A;
              wantHit =
                consec >= 2 ||
                emaRate > EMA_HOT ||
                rng() < (emaRate > EMA_WARM ? RETAL_WARM : RETAL_COOL);
            }
          } else {
            consec = 0;
            owed = 0; // кредит искупления сгорает при первом же их C
            emaRate *= (1 - EMA_A);
          }

          // 2. Любой мой фактический D порождает кредит: прощу до двух
          //    НЕМЕДЛЕННЫХ ответных ударов (осада чемпиона бьёт именно так).
          if (myLast === 'D') {
            owed = 2;
            watchArmed = true;
          }

          // 3. Эскалация: война, точечный ответ или квалификация на дойку.
          if (grievance >= WAR_AT) {
            atWar = true;
            warRounds = 0;
            oliveLeft = 0;
            anger = 0;
            owed = 0;
            consec = 0;
          } else if (wantHit && anger === 0) {
            anger = 1; // ровно один ответный удар, затем оливковая ветвь
            consec = 0;
          } else if (
            !milkBanned &&
            anger === 0 &&
            owed === 0 &&
            oppLast === 'C' &&
            rEvents >= TEST_MIN_EVENTS &&
            rAnswered <= TEST_MAX_ANSWERED &&
            emaRate <= 0.1 &&
            theirC / n >= COOP_MIN
          ) {
            milking = true; // безответный: не мстит за мои удары
            milkRounds = 0;
            milkTheirD = 0;
          }
        }

        let intent;
        if (atWar) {
          warRounds += 1;
          if (n >= 2 && theirs[n - 1] === 'C' && theirs[n - 2] === 'C') {
            // Соперник дважды подряд предложил мир — амнистия.
            // Сбрасываем и EMA: без этого кредит искупления остаётся
            // выключенным, и любое эхо тут же раскручивает новую войну.
            atWar = false;
            grievance = EXIT_G;
            emaRate = 0.06;
            owed = 0;
            consec = 0;
            anger = 0;
            oliveLeft = 0;
            intent = 'C';
          } else if (oliveLeft > 0) {
            oliveLeft -= 1;
            intent = 'C';
          } else if (warRounds > OLIVE_AFTER && rng() < OLIVE_P) {
            oliveLeft = 1; // зондаж мира: два C подряд
            intent = 'C';
          } else {
            intent = 'D';
          }
        } else if (milking) {
          milkRounds += 1;
          if (oppLast === 'D') milkTheirD += 1;
          const twoD = n >= 2 && theirs[n - 1] === 'D' && theirs[n - 2] === 'D';
          const ratioBad =
            milkRounds >= REPENT_MIN && milkTheirD / milkRounds > REPENT_RATE;
          if (twoD || ratioBad) {
            // Отпор: каюсь, дойка запрещена до конца матча.
            milking = false;
            milkBanned = true;
            owed = 2; // прощу их гнев за мою жадность
            consec = 0;
            grievance = 0.5;
            emaRate = 0.05;
            anger = 0;
            watchArmed = false;
            intent = 'C';
          } else {
            intent = rng() < MILK_D_P ? 'D' : 'C';
          }
        } else if (anger > 0) {
          anger -= 1;
          intent = 'D';
        } else if (
          probesSent < MAX_PROBES &&
          !milkBanned &&
          n >= PROBE_FROM &&
          n <= PROBE_TO &&
          owed === 0 &&
          consec === 0 &&
          oppLast === 'C' &&
          emaRate < 0.1 &&
          rng() < PROBE_P
        ) {
          probesSent += 1; // пробная атака: проверка, мстит ли он
          intent = 'D';
        } else {
          intent = 'C';
        }

        return intent;
      },
    };
  },
};
