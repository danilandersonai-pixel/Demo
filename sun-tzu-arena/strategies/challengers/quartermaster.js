'use strict';

/**
 * ДОСЬЕ · «Интендант» (Quartermaster)
 *
 * Принцип трактата:
 *   «Когда войско выступает в поход, ежедневный расход составляет тысячу
 *    золотых… Если война затягивается, оружие тупится, силы падают, казна
 *    истощается. Война любит победу и не любит продолжительности».
 *   (II. Ведение войны)
 *   Сунь-цзы во второй главе не рассуждает о доблести: он считает колесницы,
 *   волов и дневной расход казны. Интендант спрашивает не «кто прав», а
 *   «сколько это стоит и когда окупится».
 *
 * Философия (механика и арифметика):
 *   Интендант ведёт двойную бухгалтерию матча. История хранит ИСПОЛНЕННЫЕ ходы
 *   обеих сторон, поэтому накопленные счета восстанавливаются точно и за O(1):
 *       мой = 3·count(C,C) + 0·count(C,D) + 5·count(D,C) + 1·count(D,D),
 *       его = 3·count(C,C) + 5·count(C,D) + 0·count(D,C) + 1·count(D,D).
 *   Вычитание сводит всё к одной строке: разрыв = 5·(count(D,C) − count(C,D)).
 *   Взаимный мир и взаимная война на разрыв не влияют вовсе — его создают
 *   только «бесплатные удары». Это и есть книга, по которой принимаются
 *   решения; последний ход противника сам по себе не решает ничего.
 *
 *   1) Смета кампании. Дневной доход мира равен 3·q_C, где q_C — измеренная
 *      доля раундов, в которых противник ответил миром на мой мир. Дневной
 *      доход войны равен 1 + 4·q_D, где q_D — доля, в которой он ответил миром
 *      на мой удар (5 при его мире, 1 при его ударе). Обе величины не
 *      выдумываются, а ведутся в книге откликов с затуханием: старые записи
 *      списываются, важен нынешний контрагент. Режим меняется, когда одна
 *      смета обгоняет другую с запасом (гистерезис 0.35 на объявление войны,
 *      0.05 на возврат к миру) — иначе кампанию объявлял бы 5% шум.
 *      Один и тот же тест закрывает обе крайности: против того, кто не мстит,
 *      война стоит 4.7 очка против 2.95 у мира (грабёж бесплатен), а против
 *      непримиримого мир стоит 0.15 против 1.15 у войны (мир убыточен).
 *   2) Окупаемость одиночного удара. Удар по сотрудничающему даёт +2 сразу
 *      (5 вместо 3), но если он отвечает, следующий день стоит −3 (0 вместо 3).
 *      Ожидаемая прибыль = 2 − 3·(1 − q_D) = 3·q_D − 1: удар окупается ТОЛЬКО
 *      при q_D > 1/3. По сальдо арифметика другая — удар смещает разрыв на +5
 *      сейчас и максимум на −5 потом, то есть по разрыву он неубыточен всегда.
 *      Отсюда политика взыскания зависит от баланса, а не от последнего хода:
 *        — идём вровень → взыскиваем, только если 3·q_D − 1 > 0;
 *        — отстаём больше, чем объясняет шум (полоса 20 + 4·√n очков) →
 *          взыскиваем всегда: разрыв не ухудшится, а отставание сократится;
 *        — идём с отрывом ≥ 10 очков → прощаем. Отрыв дороже максимума, а
 *          затяжная война разоряет и победителя.
 *   3) Долговая книга (контриция). Каждый раунд проводится по счетам. Мой
 *      ИСПОЛНЕННЫЙ удар по чистому противнику ставит меня в долг: долг гасится
 *      сотрудничеством, ответный удар принимается молча. Это гасит эхо шума за
 *      два раунда — в том числе когда искажён мой собственный ход, ведь в
 *      историю попадает исполненное, а не задуманное. Его удар заносится в
 *      дебет, только если я не бил его в этом и в предыдущем раунде: иначе это
 *      законная месть, а не новый долг, и платить за неё второй раз глупо.
 *   4) Разведка за счёт шума. Записи по статье, которой сейчас не пользуются,
 *      медленно списываются (0.995 за раунд). Поэтому в затяжной войне оценка
 *      мира сама теряет уверенность, а 5% искажений моих собственных ходов
 *      бесплатно поставляют свежие наблюдения: исправившийся контрагент
 *      возвращает мир без отдельной статьи расходов. В мирное время тот же
 *      механизм заставляет изредка проводить платную ревизию — одну
 *      проверочную недопоставку, пока наблюдений об отклике мало. Ревизия
 *      против мстительного стоит около очка, зато открывает грабёж против
 *      доверчивого на сотню раундов раньше.
 *
 * Сильные стороны:
 *   — решает по смете и по накопленному сальдо, а не по последнему ходу:
 *     одиночная помеха тонет в статистике, а контриция гасит взаимные упрёки
 *     за два раунда, так что с «Зеркалом» и с собственной копией Интендант
 *     живёт почти на чистом мире, не проедая бюджет на эхо-войнах;
 *   — один экономический тест закрывает и грабёж доверчивых, и оборону против
 *     непримиримых, и — благодаря затуханию — противника, сменившего повадку
 *     на середине матча: смета пересчитывается за пять-шесть наблюдений.
 *
 * Слабые стороны:
 *   — открывается доверием и держит его, пока книга не набрана, поэтому первым
 *     трём-четырём ударам чистого агрессора он платит полную цену, и этих
 *     очков против него уже не вернуть;
 *   — против мстительного и абсолютно понятного противника («Зеркало»,
 *     «Мститель») дуэль структурно не выигрывается: его помехи стоят мне 5
 *     очков разрыва, а мои — ничего, и Интендант сознательно не покупает
 *     ответную войну, которая разрыв не сокращает, а доход уменьшает.
 *
 * Против кого рассчитана:
 *   Против доверчивых, непоследовательных и меняющих повадку — их он доит по
 *   первой статье и пересчитывает смету быстрее, чем они успевают снять сливки.
 *   Против безнадёжно враждебных не воюет дольше необходимого, а сразу
 *   переходит на паёк. С надёжными партнёрами держит взаимные 3.0 как самую
 *   доходную статью бюджета.
 */

var C = 'C';
var D = 'D';

// Матрица выплат — те же цифры, что в engine/payoff.js: книги должны сходиться.
var R = 3; // оба сотрудничают
var S = 0; // я сотрудничал, он предал
var T = 5; // я предал, он сотрудничал
var P = 1; // оба предали

// --- книга откликов ---
var DECAY = 0.9; // затухание записей по статье, в которую пришло наблюдение
var IDLE_FADE = 0.995; // списание записей по статье, которой не пользуются
var PRIOR_WC = 2; // вес априорного предположения о цене мира
var PRIOR_WD = 4; // вердикт «он не мстит» требует вчетверо больше доказательств
var PRIOR_C = 0.9; // пока не знаем — считаем, что на мир отвечают миром
var PRIOR_D = 0.25; // и что за удар прилетает ответ

// --- смета кампании ---
var WAR_MARGIN = 0.35; // насколько война должна обгонять мир, чтобы её объявить
var PEACE_MARGIN = 0.05; // и насколько мир должен обгонять войну, чтобы вернуться
var MIN_BOOKS = 4; // минимум наблюдений о цене мира для вердикта

// --- парламентёр: затяжная война разоряет обоих ---
var OLIVE_CEILING = 2.7; // война дешевле возможного мира — стоит проверить мир
var OLIVE_P = 0.07; // вероятность отправить парламентёра в данном раунде
var OLIVE_LEN = 2; // на сколько раундов замолкают пушки

// --- взыскание долгов ---
var PAYBACK_Q = 1 / 3; // порог окупаемости удара: 3·q − 1 > 0
var LEAD_SAFE = 10; // очков отрыва, после которых не жадничаем
var BAND_BASE = 8; // полосу разброса объясняет шум: BAND_BASE + BAND_K·√n
var BAND_K = 2.6; // (≈2σ при 5% помех, σ = 1.54·√n очков)
var BLEED_LIMIT = 2; // столько дней подряд провиант даром уходить не может

// --- ревизия ---
var PROBE_NEED = 5; // пока наблюдений об отклике на удар меньше — проверяем
var PROBE_FROM = 4;
var PROBE_TO = 130;
var PROBE_P = 0.07;

module.exports = {
  id: 'quartermaster',
  latin: 'Quartermaster',
  name: 'Интендант',
  color: '#fcd34d',
  glyph: '糧',
  family: 'challenger',
  tagline: 'Считает провиант, а не подвиги',
  dossier: {
    principle: '«Война любит победу и не любит продолжительности» — II. Ведение войны',
    philosophy:
      'Ведёт двойную бухгалтерию матча: накопленные очки свои и чужие восстанавливает из ' +
      'истории точно и за O(1), а решает по смете и по сальдо, а не по последнему ходу. ' +
      'Разрыв сводится к одной строке — 5·(count(D,C) − count(C,D)); взаимный мир и взаимная ' +
      'война на него не влияют. Дневной доход мира равен 3·q_C, дневной доход войны — ' +
      '1 + 4·q_D, где обе доли измерены по книге откликов с затуханием; режим меняется, ' +
      'когда одна смета обгоняет другую с запасом (0.35 на объявление войны, 0.05 на ' +
      'возврат), иначе кампанию объявлял бы 5% шум. Один и тот же тест закрывает обе ' +
      'крайности: против не мстящего война даёт 4.70 против 2.95 у мира, против ' +
      'непримиримого мир даёт 0.15 против 1.15 у войны. Одиночный удар окупается только при ' +
      'q_D > 1/3 (2 − 3·(1 − q_D) > 0), но по разрыву он неубыточен всегда — поэтому вровень ' +
      'Интендант взыскивает лишь при 3·q_D − 1 > 0, отставая больше полосы шума ' +
      '(20 + 4·√n очков) взыскивает всегда, а с отрывом в 10 очков прощает: отрыв дороже ' +
      'максимума. Долговая книга с контрицией гасит эхо шума за два раунда, признавая ' +
      'собственный искажённый удар своим долгом, а разведку в затяжной войне оплачивает сам ' +
      'шум: 5% искажений дают бесплатные наблюдения о том, не исправился ли контрагент.',
    strengths: [
      'Решает по смете и накопленному сальдо — помеха не сбивает курс, эхо гаснет за два раунда',
      'Один экономический тест закрывает и грабёж доверчивых, и оборону от непримиримых, и смену повадки на середине матча'
    ],
    weaknesses: [
      'Открывается доверием: первым ударам чистого агрессора платит полную цену, и этих очков не вернуть',
      'Дуэль с «Зеркалом» и «Мстителем» структурно не выигрывается — и он сознательно не покупает войну, которая разрыв не сокращает'
    ],
    targets:
      'Против доверчивых, непоследовательных и меняющих повадку — их он доит и пересчитывает ' +
      'смету быстрее, чем они снимут сливки; против безнадёжно враждебных не воюет дольше ' +
      'необходимого; с надёжными держит взаимные 3.0'
  },

  create: function (api) {
    var coin = api && typeof api.random === 'function' ? api.random : null;

    // Книги учёта живут в замыкании: один комплект на матч, ничего глобального.
    var posted = 0; // сколько раундов уже проведено по книгам
    var iOwe = false; // мой исполненный удар лёг на чистого противника
    var heOwes = false; // его удар лёг на чистого меня и не был местью
    var wC = 0; // вес наблюдений «я мир → его ответ»
    var sC = 0; // из них мирных ответов
    var wD = 0; // вес наблюдений «я удар → его ответ»
    var sD = 0; // из них мирных ответов
    var atWar = false; // текущий режим бюджета
    var oliveLeft = 0; // сколько раундов перемирия ещё оплачено
    var bleed = 0; // сколько дней подряд провиант уходит даром

    return {
      move: function (h) {
        var n = h.length;

        // Первый раунд — открытый кредит: мир самая доходная статья, и дешевле
        // всего начать проверку его доступности с собственного взноса.
        if (n === 0) return C;

        // --- проводка новых раундов по книгам, O(1) на раунд ---
        while (posted < n) {
          var m = h.mine(posted); // мой ИСПОЛНЕННЫЙ ход: шум уже учтён
          var o = h.opp(posted);
          var priorMine = posted > 0 ? h.mine(posted - 1) : null;
          var iOweBefore = iOwe;
          var heOwesBefore = heOwes;

          // Долговая книга.
          iOwe = m === D && !heOwesBefore;
          heOwes = o === D && !iOweBefore && m !== D && priorMine !== D;
          if (heOwes) bleed += 1;
          else if (o === C) bleed = 0;

          // Книга откликов: его ход — это ответ на мой предыдущий.
          if (priorMine !== null) {
            var reply = o === C ? 1 : 0;
            if (priorMine === D) {
              wD = wD * DECAY + 1;
              sD = sD * DECAY + reply;
              wC = wC * IDLE_FADE;
              sC = sC * IDLE_FADE;
            } else {
              wC = wC * DECAY + 1;
              sC = sC * DECAY + reply;
              wD = wD * IDLE_FADE;
              sD = sD * IDLE_FADE;
            }
          }

          posted += 1;
        }

        // --- сальдо матча: оба накопленных счёта точно, за O(1) ---
        var cc = h.count(C, C);
        var cd = h.count(C, D);
        var dc = h.count(D, C);
        var dd = h.count(D, D);
        var myScore = R * cc + S * cd + T * dc + P * dd;
        var hisScore = R * cc + T * cd + S * dc + P * dd;
        var lead = myScore - hisScore; // = 5 · (dc − cd)
        var band = BAND_BASE + BAND_K * Math.sqrt(n); // что объясняет шум

        // --- смета: дневной доход мира против дневного дохода войны ---
        var qC = (sC + PRIOR_WC * PRIOR_C) / (wC + PRIOR_WC);
        var qD = (sD + PRIOR_WD * PRIOR_D) / (wD + PRIOR_WD);
        var peaceValue = R * qC; // 3 · p(он C | я C)
        var warValue = P + (T - P) * qD; // 1 + 4 · p(он C | я D)

        if (atWar) {
          // Парламентёр ответил миром — кампания окончена, не дожидаясь книг.
          if (oliveLeft > 0 && h.opp(-1) === C) {
            atWar = false;
            oliveLeft = 0;
          } else if (oliveLeft > 0) {
            oliveLeft -= 1; // пушки молчат: покупаем свежую запись о цене мира
            return C;
          } else if (peaceValue > warValue + PEACE_MARGIN) {
            atWar = false;
          } else if (warValue < OLIVE_CEILING && coin && coin() < OLIVE_P) {
            // Война приносит меньше, чем мог бы принести мир, а оценка мира
            // устарела. Парламентёр стоит один день — молчание стоит два очка
            // в день. «Война любит победу и не любит продолжительности».
            // Час отправки выбирает жребий: иначе две одинаковые ставки
            // разошлись бы фазами и не встретились никогда.
            oliveLeft = OLIVE_LEN - 1;
            return C;
          }
        } else if (wC >= MIN_BOOKS && warValue > peaceValue + WAR_MARGIN) {
          atWar = true;
          oliveLeft = 0;
        }
        if (atWar) return D;

        // --- мирная бухгалтерия: свои долги гасятся первыми ---
        if (iOwe) return C;

        // --- взыскание по его долгу: решение от сальдо ---
        if (heOwes) {
          // Два дня подряд провиант уходит даром — третий отпускать нельзя,
          // сколько бы ни стоила месть: это уже не помеха, а система.
          if (bleed >= BLEED_LIMIT) return D;
          if (lead >= LEAD_SAFE) return C; // отрыв дороже максимума
          if (lead <= -band) return D; // отстаём: по разрыву удар неубыточен
          return qD > PAYBACK_Q ? D : C; // вровень: только если 3·q − 1 > 0
        }

        // --- ревизия, пока книга откликов на удар пуста ---
        if (
          coin &&
          wD < PROBE_NEED &&
          n >= PROBE_FROM &&
          n <= PROBE_TO &&
          lead < LEAD_SAFE &&
          coin() < PROBE_P
        ) {
          return D;
        }
        return C;
      }
    };
  }
};
