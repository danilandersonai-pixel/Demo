var BY_ID = new Map();
var BY_ALIAS = new Map();

TERMS.forEach(function (t) {
  BY_ID.set(t.id, t);
  BY_ALIAS.set(t.term.toLowerCase(), t);
  (t.aliases || []).forEach(function (a) {
    BY_ALIAS.set(String(a).toLowerCase(), t);
  });
});

function get(idOrAlias) {
  if (!idOrAlias) return null;
  var key = String(idOrAlias).toLowerCase();
  return BY_ID.get(key) || BY_ALIAS.get(key) || null;
}

function all() {
  return TERMS.slice().sort(function (a, b) {
    return a.term.localeCompare(b.term, 'ru');
  });
}

function search(query) {
  var q = String(query || '').trim().toLowerCase();
  if (!q) return all();
  return all().filter(function (t) {
    if (t.term.toLowerCase().indexOf(q) !== -1) return true;
    if (t.text.toLowerCase().indexOf(q) !== -1) return true;
    return (t.aliases || []).some(function (a) {
      return String(a).toLowerCase().indexOf(q) !== -1;
    });
  });
}

module.exports = {
  TERMS: TERMS,
  get: get,
  all: all,
  search: search,
  count: TERMS.length
};
