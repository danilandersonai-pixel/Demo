// «Зеркало» (TitForTat) — классика, победитель турниров Аксельрода.
// Принцип: начни с добра, дальше повторяй последний ход оппонента.
// Философия: ясность. Добро на добро, удар на удар, ни злобы, ни зависти.
// Сильные стороны: мгновенно наказывает и мгновенно прощает; никого не
// эксплуатирует, но и себя в обиду не даёт.
// Слабые стороны: при шуме застревает в эхо-войнах «D-C-D-C» с себе
// подобными; не умеет доить доверчивых.
// Против кого рассчитан: универсален; лучший ответ большинству соседей.
// ──────────────────────────────────────────────────────────────────────

import { C } from '../engine/game.js';

export default {
  id: 'tit-for-tat',
  name: 'Зеркало',
  epithet: 'око за око',
  color: '#4fc3f7',
  dossier: {
    quote: 'Я — лишь отражение. Улыбнись мне, и я улыбнусь в ответ.',
    principle: 'Первый ход — C; дальше копировать последний фактический ход оппонента.',
    strengths: ['Не проигрывает ни одному матчу больше, чем на одно предательство', 'Прозрачен: с ним быстро учатся сотрудничать'],
    weaknesses: ['Шум запускает эхо-войны с такими же зеркалами', 'Никогда не эксплуатирует — упускает T=5 против доверчивых'],
    targets: 'Универсальный страж кооперации; опора союза против агрессоров.',
  },
  create() {
    return {
      move(mine, theirs) {
        if (theirs.length === 0) return C;
        return theirs[theirs.length - 1];
      },
    };
  },
};
