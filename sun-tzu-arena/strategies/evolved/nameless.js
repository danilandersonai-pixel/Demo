// «Безымянный» (Nameless) — стратегия, выведенная генетическим отбором.
// Родословная: 150 поколений, популяция 64, сид 42
// (sim/evolve.js --seed 42). Никто её не писал: геном (память на два
// последних раунда, 21 ген) отобран турнирами, кроссовером и мутацией.
// Автоинтерпретация: первый ход — предательство;
// доля D в геноме 62 %; наказывает предательство в 60 %
// состояний; совпадение с Зеркалом 50 %, с Прагматиком 60 %.
// Файл сгенерирован автоматически — не редактировать вручную.
// ──────────────────────────────────────────────────────────────────────

const GENES = ["D","C","C","C","D","C","D","D","C","D","D","D","D","D","C","D","D","C","D","D","C"];

function outcomeIndex(my, opp) {
  return (my === 'D' ? 2 : 0) + (opp === 'D' ? 1 : 0);
}

export default {
  id: 'nameless',
  name: 'Безымянный',
  epithet: 'рождённый отбором',
  color: '#c9c2ae',
  dossier: {
    quote: 'У лучшего полководца нет имени: его выковала сама война.',
    principle: 'Таблица ответов на исходы двух последних раундов, выведенная генетическим алгоритмом (150 поколений коэволюции).',
    strengths: ['Поведение отобрано против живой популяции, а не придумано', 'Совпадение с Зеркалом 50 %, с Прагматиком 60 % — но не копия ни того, ни другого'],
    weaknesses: ['Память всего два раунда: длинные паттерны не распознаёт', 'Отбор шёл против своих — незнакомые стили могут найти дыру'],
    targets: 'Против тех, кто похож на среду его эволюции: адаптивных кооператоров.',
    genome: GENES.join(''),
  },
  create() {
    return {
      move(mine, theirs) {
        const r = mine.length;
        if (r === 0) return GENES[0];
        const last = outcomeIndex(mine[r - 1], theirs[r - 1]);
        if (r === 1) return GENES[1 + last];
        const prev = outcomeIndex(mine[r - 2], theirs[r - 2]);
        return GENES[5 + prev * 4 + last];
      },
    };
  },
};
