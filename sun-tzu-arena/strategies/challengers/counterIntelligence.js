'use strict';

/**
 * ДОСЬЕ · «Контрразведка» (CounterIntelligence) — стратегия-претендент
 *
 * Принцип трактата:
 *   «Война — это путь обмана». (I. Предварительные расчёты)
 *   «Знание положения противника можно получить только от людей». (XIII. Использование шпионов)
 *   Обман работает ровно до тех пор, пока его не с чем сравнить. Поэтому
 *   Контрразведка не спрашивает «что он сделал сейчас» — она спрашивает
 *   «изменился ли он по сравнению с собой прежним».
 *
 * Философия:
 *   Обычное «Зеркало» реагирует на последний ход. Против того, кто восемнадцать
 *   раундов играет святого, а на девятнадцатом снимает маску, это опоздание
 *   ровно на один ход и на все очки, которые уже утекли. Контрразведка ведёт
 *   досье и сравнивает два портрета одного и того же человека — ранний и
 *   сегодняшний.
 *
 *   ОТСЕВ ШУМА И ПРОВОКАЦИЙ. Улика — не всякое предательство. Ход противника
 *   идёт в дело, только если он был СВОБОДНЫМ: в предыдущем раунде я исполнил C,
 *   значит, поводов у него не было. Всё, что следует за моим собственным
 *   предательством (в том числе за приказом, искажённым помехой), из статистики
 *   вычёркивается — иначе эхо взаимных упрёков само себя объявит заговором.
 *   Свой сорвавшийся приказ Контрразведка обнаруживает, сравнивая то, что
 *   вернула, с h.mine(-1), и два раунда молчит, не отвечая на заслуженную кару.
 *
 *   ЧЕТЫРЕ УЛИКИ. Приговор выносится, если сработал хоть один канал:
 *     1. Вспышка — серия из 4 предательств подряд, НАЧАТАЯ без повода.
 *        Четыре подряд при 5% помех — событие вероятности 6·10⁻⁶ за позицию;
 *        это снятая маска, а не сбой связи. Ловит резкий разворот «Приманки».
 *     2. Открытая вражда — на первых же свободных наблюдениях доля
 *        предательств ≥ 30%. Это не обман, а честная война; мягкость к ней
 *        не относится.
 *     3. Накопитель улик (CUSUM) — сумма превышений над опорным уровнем 0.11
 *        (двойной шум с запасом), обнуляемая снизу. Ловит МЕДЛЕННЫЙ дрейф,
 *        который ни одно окно поодиночке не отличит от помех, — ту самую
 *        «жатву», что подмешивают в мирную игру после сотни раундов.
 *     4. Сличение портретов — двухвыборочный z-критерий: ранний профиль
 *        (первые 30 свободных раундов, потом заморожен) против скользящего
 *        окна последних 25. Улика засчитывается при расхождении ≥ 0.18 И
 *        значимости z ≥ 2.2 — поправка на то, что одни только помехи дают
 *        около 5% расхождения в обе стороны.
 *
 *   ДВА КУРСА. До приговора — мягкость: наказание ровно на один раунд за
 *   каждое свободное предательство (чтобы никто не занёс тебя в картотеку
 *   «не мстит»), а сразу за ним два безусловных шага навстречу, которые
 *   гарантированно вытаскивают пару из противофазы. После приговора возврата
 *   нет: строгое зеркало без снисхождения, а если досье показывает, что
 *   противник не отвечает на удар (P(он C | я D) ≥ 0.45 при ≥5 наблюдениях),
 *   курс становится окончательным — вечное предательство. Единственная
 *   поблажка военного времени — восстановление СВЯЗИ, а не доверия: увидев
 *   чистую противофазу (D,C) → (C,D), Контрразведка один раз ходит C, потому
 *   что противник уже отвечает на её мирный ход, и пара мгновенно
 *   синхронизируется на 3.0 вместо вечных 2.5.
 *
 * Сильные стороны:
 *   — ловит смену режима по существу дела, а не по последнему ходу: резкий
 *     разворот — за 3–4 раунда, медленный дрейф — накопителем улик;
 *   — фильтр «свободных» ходов делает её невосприимчивой к собственному шуму:
 *     эхо взаимных наказаний не попадает в статистику и не рождает ложный
 *     приговор, поэтому она уживается со своей же копией;
 *   — наказывает каждое свободное предательство ровно один раз, поэтому её
 *     нельзя занести в список безответных и начать доить;
 *   — оливковая ветвь и резинхронизация не дают ей утонуть в противофазе,
 *     в которой «Зеркало» теряет треть очков.
 *
 * Слабые стороны:
 *   — приговор необратим: одна серия из четырёх помех подряд (или столь же
 *     редкое совпадение) навсегда лишает честного соперника снисхождения;
 *   — медленный дрейф всё равно требует десятков раундов накопления улик —
 *     часть урожая обманщик успевает собрать;
 *   — против того, кто предаёт стабильно и чуть ниже всех порогов (около
 *     10–15% свободных предательств), остаётся мягкой и переплачивает;
 *   — два шага навстречу после наказания — бесплатный раунд для того,
 *     кто бьёт строго через раз и укладывается в пороги.
 *
 * Против кого рассчитана:
 *   Против перевёртышей — «Приманки» с её маской на 18 раундов и «Терпения»
 *   с жатвой после 120-го; шире — против любого, чей ранний портрет не
 *   совпадает с сегодняшним. Против ровных (и добрых, и открыто злых) она
 *   ведёт себя как обычная сдержанная стратегия и ничего не теряет.
 */

var C = 'C';
var D = 'D';

// --- пороги детекторов -------------------------------------------------------
var BASE_TARGET = 30; // свободных раундов в раннем портрете, потом заморозка
var RECENT_WINDOW = 25; // скользящее окно «сегодняшнего» портрета
var MIN_RECENT = 12; // меньше наблюдений — сличать нечего
var Z_CRIT = 2.2; // порог значимости расхождения портретов
var MIN_GAP = 0.18; // расхождение ниже — в пределах помех
var CUSUM_REF = 0.11; // опорный уровень накопителя (шум 0.05 + запас)
var CUSUM_LIMIT = 3.2; // накопленная улика, после которой выносится приговор
var RUN_TRIGGER = 4; // серия подряд, начатая без повода, — снятая маска
var OPEN_MIN = 10; // минимум свободных наблюдений для приговора «открытая вражда»
var OPEN_RATE = 0.3; // доля свободных предательств, которую не спишешь на шум

// --- поведение ---------------------------------------------------------------
var OLIVE = 2; // безусловных шага навстречу после наказания
var CONTRITION = 2; // раунды покаяния за собственный сорвавшийся приказ
var MILK_COOP = 0.45; // P(он C | я D) выше — он не мстит, выгоднее доить
var MILK_SAMPLES = 5; // меньше наблюдений — приговор о безответности не выносим
var MAX_RESYNC = 20; // предел попыток восстановить связь в противофазе

module.exports = {
  id: 'counterIntelligence',
  latin: 'CounterIntelligence',
  name: 'Контрразведка',
  color: '#7dd3fc',
  glyph: '諜',
  family: 'challenger',
  tagline: 'Сличает сегодняшний портрет противника с ранним',
  dossier: {
    principle: '«Война — это путь обмана» — I. Предварительные расчёты',
    philosophy:
      'Ведёт досье и сравнивает противника не с другими, а с ним же прежним. ' +
      'Уликой считает только «свободное» предательство — то, которому не ' +
      'предшествовал мой собственный удар или сорвавшийся приказ. Резкий ' +
      'разворот ловит вспышкой из четырёх ходов подряд, медленный дрейф — ' +
      'накопителем улик и z-сличением раннего окна с недавним. Приговор ' +
      'необратим: мягкость до него, строгое зеркало и доение — после.',
    strengths: [
      'Ловит смену режима: резкий разворот за 3–4 раунда, медленный дрейф — накопителем улик',
      'Фильтр «свободных» ходов отсеивает собственный шум — уживается со своей копией'
    ],
    weaknesses: [
      'Приговор необратим: редкая серия помех навсегда лишает честного снисхождения',
      'К тому, кто предаёт стабильно и чуть ниже порогов, остаётся мягкой и переплачивает'
    ],
    targets: 'Против перевёртышей: «Приманка» с маской на 18 раундов, «Терпение» с поздней жатвой'
  },

  create: function () {
    // --- что я приказал в прошлом раунде (для поимки собственного срыва) ---
    var intended = C;

    // --- курс ---
    var exposed = false; // обманщик раскрыт, назад дороги нет
    var hostile = false; // он доказал, что не отвечает на удар → вечное D
    var contrite = 0; // раунды покаяния за собственный сорвавшийся приказ
    var olive = 0; // раунды безусловного шага навстречу
    var resyncUsed = 0;

    // --- досье ---
    var seen = 0; // сколько раундов истории уже разобрано
    var run = 0; // текущая серия предательств оппонента
    var runFree = false; // была ли серия начата без повода с моей стороны
    var burst = false; // сработал детектор вспышки

    var baseDef = 0; // ранний портрет
    var baseN = 0;
    var baseLocked = false;

    var buf = []; // скользящее окно «сегодняшнего» портрета
    var bufSum = 0;

    var cusum = 0; // накопитель улик
    var freeDef = 0; // кумулятивно по всем свободным раундам
    var freeN = 0;

    /**
     * Разбор новых раундов истории. Улика — только «свободный» ход противника:
     * такой, перед которым я исполнил C и, значит, повода не давал. Всё, что
     * следует за моим предательством (включая искажённый помехой приказ),
     * из статистики вычёркивается — это его ответ, а не его природа.
     */
    function ingest(h) {
      var n = h.length;
      var i, oppMove, prevMine, free, def;

      for (i = seen; i < n; i++) {
        oppMove = h.opp(i);
        prevMine = i > 0 ? h.mine(i - 1) : C;
        free = prevMine === C;
        def = oppMove === D ? 1 : 0;

        // Вспышка: серия подряд, НАЧАТАЯ без повода.
        if (def) {
          if (run === 0) runFree = free;
          run += 1;
          if (run >= RUN_TRIGGER && runFree) burst = true;
        } else {
          run = 0;
          runFree = false;
        }

        if (!free) continue;

        freeN += 1;
        freeDef += def;

        if (!baseLocked) {
          baseN += 1;
          baseDef += def;
          if (baseN >= BASE_TARGET) baseLocked = true;
        } else {
          buf.push(def);
          bufSum += def;
          if (buf.length > RECENT_WINDOW) bufSum -= buf.shift();
          cusum = cusum + def - CUSUM_REF;
          if (cusum < 0) cusum = 0;
        }
      }

      seen = n;
    }

    /** Вынесение приговора. Необратимо. */
    function judge() {
      if (exposed) return;

      // 1. Вспышка — маска снята рывком.
      if (burst) {
        exposed = true;
        return;
      }

      // 2. Открытая вражда — не обман, но и не повод для мягкости.
      if (freeN >= OPEN_MIN && freeDef / freeN >= OPEN_RATE) {
        exposed = true;
        return;
      }

      // 3. Накопитель улик — медленный дрейф.
      if (cusum >= CUSUM_LIMIT) {
        exposed = true;
        return;
      }

      // 4. Сличение раннего портрета с сегодняшним.
      if (baseLocked && buf.length >= MIN_RECENT) {
        var nr = buf.length;
        var pr = bufSum / nr;
        var pb = baseDef / baseN;
        var gap = pr - pb;
        if (gap >= MIN_GAP) {
          var pooled = (bufSum + baseDef) / (nr + baseN);
          var se = Math.sqrt(pooled * (1 - pooled) * (1 / nr + 1 / baseN));
          if (se > 0 && gap / se >= Z_CRIT) exposed = true;
        }
      }
    }

    /** Курс военного времени: снисхождения нет, есть только расчёт. */
    function warPath(h) {
      if (hostile) return D;

      // Он не отвечает на удар — значит, его нужно доить, а не зеркалить.
      if (h.oppSamplesAfter(D) >= MILK_SAMPLES && h.oppCoopAfter(D, 0) >= MILK_COOP) {
        hostile = true;
        return D;
      }

      // Восстановление связи, а не доверия: чистая противофаза (D,C) → (C,D)
      // означает, что он уже отвечает на мой мирный ход. Один C синхронизирует
      // пару на 3.0 вместо вечного размена по 2.5.
      if (
        resyncUsed < MAX_RESYNC &&
        h.length >= 2 &&
        h.mine(-1) === C &&
        h.opp(-1) === D &&
        h.mine(-2) === D &&
        h.opp(-2) === C
      ) {
        resyncUsed += 1;
        return C;
      }

      return h.opp(-1) === D ? D : C;
    }

    function decide(h) {
      var n = h.length;
      if (n === 0) return C;

      // Собственный приказ исказила помеха — он видел не то, что я приказывал.
      // Его ответный удар заслужен: два раунда молчим и не считаем это уликой.
      if (h.mine(-1) !== intended) {
        contrite = CONTRITION;
        olive = 0;
      }

      ingest(h);
      judge();

      if (exposed) return warPath(h);

      var last = h.opp(-1);
      var provoked = h.mine(-2) === D; // его ход был ответом на моё предательство

      if (contrite > 0) {
        contrite -= 1;
        return C;
      }

      if (olive > 0) {
        // Он бьёт по протянутой руке, и бьёт без повода — ветвь отзывается.
        if (last === D && !provoked) {
          olive = 0;
          return D;
        }
        olive -= 1;
        return C;
      }

      if (last === C) return C;

      // Ответ на моё же наказание — ожидаемо, эхо гасим молча.
      if (provoked) return C;

      // Свободное предательство: ровно один раунд возмездия, чтобы меня не
      // занесли в картотеку безответных, и сразу два шага навстречу.
      olive = OLIVE;
      return D;
    }

    return {
      move: function (h) {
        var m = decide(h);
        intended = m;
        return m;
      }
    };
  }
};
