// ДОСЬЕ: «Союзник» (ch-alliance)
// ----------------------------------------------------------------------------
// Принцип (глава III, «Стратегическое нападение»): лучшее — разбить замыслы
// врага, затем его союзы, и лишь потом войска. В эволюционном турнире
// выживает не победитель матчей, а тот, чей блок кооперации даёт популяции
// наибольшую среднюю выплату. Эта стратегия — клей такого блока.
//
// Философия: никогда не начинать войну первой; любой одиночный удар считать
// шумом, а не замыслом; собственные срывы (в т.ч. шумовые) искупать, безропотно
// принимая ответные удары, чтобы не раскручивать спирали мести; и только
// серийного агрессора, чьи удары складываются в замысел, изолировать войной —
// не кормить хищника, но и в войне изредка протягивать оливковую ветвь.
//
// Механика:
//  * Мир по умолчанию: намерение всегда 'C'.
//  * «Кредит искупления» (owed): после моего фактического 'D' я прощаю до
//    2 ответных ударов (шумовой срыв) или 1 (моё намеренное наказание) —
//    это гасит эхо у зеркальных стратегий и двойной ответ чемпиона в осаде.
//    Невостребованный кредит быстро сгорает.
//  * Терпимость: одиночное непрощённое 'D' соперника — просто обида, без
//    ответа. Два подряд — ровно один ответный удар и немедленный возврат к 'C'.
//  * «Счёт обид» (grievance): каждое непрощённое 'D' даёт +1, счёт затухает
//    (x0.85/раунд). Шум 5% держит его ~0.35; серийный агрессор или альтернатор
//    пробивает порог 3.2 → тотальная война ('D' каждый раунд).
//  * В войне: редкие зондажи мира (двойное 'C' с вероятностью ~4.5%/раунд
//    после 12 раундов войны); выход из войны — только если соперник сыграл
//    'C' дважды подряд; после мира — амнистия, но счёт обид стартует с 1.2
//    (рецидивиста изолируем быстрее).
//
// Сильные стороны:
//  * Почти идеальный селф-матч при шуме 5%: одиночные сбои гасятся без эха.
//  * Не раскручивает спирали ни с зеркалом (TFT), ни с «Полководцем» во всех
//    трёх фазах, включая осаду «за одно D — два удара».
// Слабые стороны:
//  * Против чистого AllD платит за миролюбие чуть дороже мгновенного Grim
//    (поздний триггер войны, периодические зондажи мира уходят в молоко).
//  * Точечный паразит, бьющий строго после моих срывов, снимает пару лишних
//    очков безнаказанно (кредит искупления прощает его удары).
// Против кого рассчитана: кооперативный блок и чемпион «Полководец»; серийных
// агрессоров изолирует, альтернаторов переигрывает уже в режиме войны.
// ----------------------------------------------------------------------------

export default {
  id: 'ch-alliance',
  name: 'Союзник',
  epithet: 'щит союза',
  color: '#5eead4',
  dossier: {
    quote:
      'Сто побед в ста сражениях — не вершина искусства: вершина — разбить замысел врага, не разрушив мира.',
    principle:
      'Никогда не бьёт первым: одиночные удары списывает на шум, свои срывы искупает, серии карает одним ударом, а серийных агрессоров изолирует войной с редкими предложениями мира.',
    strengths: [
      'Почти идеальный селф-матч при шуме 5%: одиночные сбои гасятся без эха и спиралей',
      'Устойчив к фазам чемпиона: искупление своих случайных D переживает даже осаду «за одно D — два удара»',
    ],
    weaknesses: [
      'Против чистого AllD чуть дороже мгновенного Grim: поздний триггер войны и зондажи мира стоят очков',
      'Точечный паразит, бьющий строго после чужих срывов, снимает пару лишних очков безнаказанно',
    ],
    targets:
      'Кооперативный блок и чемпион «Полководец» во всех трёх фазах; серийные агрессоры и альтернаторы изолируются войной.',
  },

  create(rng) {
    const OWED_CAP = 3; // потолок кредита искупления
    const DECAY = 0.85; // затухание счёта обид за раунд
    const WAR_AT = 3.2; // порог тотальной войны
    const EXIT_G = 1.2; // счёт обид после амнистии (рецидивиста изолируем быстрее)
    const PROBE_AFTER = 12; // раундов войны до первых зондажей мира
    const PROBE_P = 0.045; // вероятность зондажа (двойное 'C') за раунд войны

    let owed = 0; // сколько ответных ударов я прощу (искупление моих D)
    let consec = 0; // непрощённые 'D' соперника подряд
    let grievance = 0; // затухающий счёт обид
    let anger = 0; // запланированные ответные удары (0 или 1)
    let atWar = false;
    let warRounds = 0;
    let probeLeft = 0; // сколько ещё 'C' доиграть в текущем зондаже
    let intendedPrev = 'C'; // что я НАМЕРЕВАЛСЯ сыграть в прошлом раунде

    return {
      move(mine, theirs) {
        const n = mine.length;
        if (n === 0) {
          intendedPrev = 'C';
          return 'C';
        }
        const myLast = mine[n - 1];
        const oppLast = theirs[n - 1];

        if (!atWar) {
          grievance *= DECAY;

          // 1. Ход соперника: прощён (искупление), стерплен или записан в обиды.
          if (oppLast === 'D') {
            if (owed > 0) {
              owed -= 1; // его удар — законная расплата за мой D
              consec = 0;
            } else {
              consec += 1;
              grievance += 1;
            }
          } else {
            consec = 0;
            if (owed > 0) owed -= 1; // невостребованный кредит сгорает
          }

          // 2. Мой фактический D порождает кредит искупления:
          //    шумовой срыв — двойной (осада чемпиона бьёт дважды),
          //    намеренное наказание — одинарный (гасит эхо контрудара).
          if (myLast === 'D') {
            owed = Math.min(OWED_CAP, owed + (intendedPrev === 'C' ? 2 : 1));
          }

          // 3. Эскалация: война по счёту обид, иначе — точечный ответ на серию.
          if (grievance >= WAR_AT) {
            atWar = true;
            warRounds = 0;
            probeLeft = 0;
            anger = 0;
            owed = 0;
            consec = 0;
          } else if (consec >= 2 && anger === 0) {
            anger = 1; // ровно один ответный удар, затем оливковая ветвь
            consec = 0;
          }
        }

        let intent;
        if (atWar) {
          warRounds += 1;
          if (n >= 2 && theirs[n - 1] === 'C' && theirs[n - 2] === 'C') {
            // Соперник дважды подряд предложил мир — амнистия.
            atWar = false;
            grievance = EXIT_G;
            owed = 0;
            consec = 0;
            anger = 0;
            probeLeft = 0;
            intent = 'C';
          } else if (probeLeft > 0) {
            probeLeft -= 1;
            intent = 'C';
          } else if (warRounds > PROBE_AFTER && rng() < PROBE_P) {
            probeLeft = 1; // зондаж мира: два 'C' подряд
            intent = 'C';
          } else {
            intent = 'D';
          }
        } else if (anger > 0) {
          anger -= 1;
          intent = 'D';
        } else {
          intent = 'C';
        }

        intendedPrev = intent;
        return intent;
      },
    };
  },
};
