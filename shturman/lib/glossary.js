function findTerm(query) {
  var q = String(query || '').toLowerCase().trim();
  for (var i = 0; i < TERMS.length; i++) {
    if (TERMS[i].term.toLowerCase().indexOf(q) !== -1) return TERMS[i];
  }
  return null;
}

