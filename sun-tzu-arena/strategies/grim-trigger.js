// ДОСЬЕ ────────────────────────────────────────────────────────────────
// «Мститель» (GrimTrigger) — классика.
// Принцип: одно предательство — вечная война.
// Философия: доверие даётся один раз. Кто его предал — враг навсегда.
// Сильные стороны: абсолютное сдерживание; эксплуатировать его невозможно.
// Слабые стороны: при 5 % шума любой длинный матч почти гарантированно
// скатывается в вечную войну — даже с друзьями; не прощает случайности.
// Против кого рассчитан: против эксплуататоров и пробующих на прочность.
// ──────────────────────────────────────────────────────────────────────

import { C, D } from '../engine/game.js';

export default {
  id: 'grim-trigger',
  name: 'Мститель',
  epithet: 'вечная война за одно предательство',
  color: '#a1662f',
  dossier: {
    quote: 'Я прощаю всё, кроме первого раза.',
    principle: 'Кооперировать, пока оппонент чист; после первого его D — предавать вечно.',
    strengths: ['Идеальное сдерживание: эксплуатация невозможна в принципе', 'Против чистых кооператоров неотличим от святого'],
    weaknesses: ['Шум = смертный приговор дружбе: одно случайное D, и мир рухнул', 'Платит за месть полную цену: вечная война даёт всего 1.0'],
    targets: 'Против зондирующих и эксплуататоров; в шумном мире бьёт и по своим.',
  },
  create() {
    let provoked = false;
    return {
      move(mine, theirs) {
        if (!provoked && theirs.length > 0 && theirs[theirs.length - 1] === D) {
          provoked = true;
        }
        return provoked ? D : C;
      },
    };
  },
};
