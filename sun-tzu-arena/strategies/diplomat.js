// ДОСЬЕ ────────────────────────────────────────────────────────────────
// «Дипломат» (Diplomat) — авторская, направление «Победа без боя».
// Принцип из трактата (по мотивам гл. III): «Высшее искусство войны —
// покорить врага, не сражаясь».
// Философия: наказание — не месть, а инструмент возврата к миру. Дозируй
// его точно: один ответный удар — и сразу протянутая рука. Если же
// предателем оказался ты сам (шум исказил твой ход) — извинись: два
// раунда безусловной кооперации, чужое возмездие снеси молча.
// Механика (контрит + великодушие + оливковая ветвь):
//  • великодушие: чужое D прощается с вероятностью 15 % (амортизация шума);
//  • наказание: ровно один ответный D;
//  • оливковая ветвь: сразу после наказания — C безусловно;
//  • контрит: если мой фактический ход D при задуманном C — «мне стыдно»,
//    два раунда C, ответное возмездие не караю.
// Сильные стороны: лучший друг шумной среды — эхо-войны гаснут за 1–2
// раунда; кооператоры рядом с ним процветают.
// Слабые стороны: агрессор доит его великодушие и оливковые ветви;
// эксплуататор получает от него больше, чем от Зеркала.
// Против кого рассчитан: против своих же — он максимизирует доход блока
// кооператоров в мире, где 5 % ходов врут.
// ──────────────────────────────────────────────────────────────────────

import { C, D } from '../engine/game.js';

const GENEROSITY = 0.15; // вероятность простить чужое D

export default {
  id: 'diplomat',
  name: 'Дипломат',
  epithet: 'покорить, не сражаясь',
  color: '#5fd0c0',
  dossier: {
    quote: 'Высшее искусство войны — покорить врага, не сражаясь.',
    principle: 'Наказывать ровно одним ударом и сразу предлагать мир; свои случайные предательства искупать двумя раундами кооперации.',
    strengths: ['Гасит эхо-войны от шума за 1–2 раунда', 'Максимизирует доход блока кооператоров', 'Контрит-механика: отличает свой сбой от чужой агрессии'],
    weaknesses: ['Великодушие и оливковые ветви доятся вечным агрессором', 'Отдаёт эксплуататору больше, чем Зеркало'],
    targets: 'Против шума и своих: создан удерживать союз кооператоров в мире, где ходы врут.',
  },
  create(rng) {
    let intendedLast = null; // мой задуманный ход прошлого раунда
    let contrition = 0; // сколько раундов извинений осталось
    let oliveBranch = false; // я только что наказал — предлагаю мир
    return {
      move(mine, theirs) {
        const r = mine.length;
        let m;
        if (r === 0) {
          m = C;
        } else {
          const myActual = mine[r - 1];
          const oppLast = theirs[r - 1];
          if (contrition > 0) {
            // Извиняюсь за свой искажённый ход; возмездие сношу молча.
            contrition--;
            m = C;
          } else if (myActual === D && intendedLast === C) {
            // Шум сделал меня предателем — искупаю два раунда.
            contrition = 1; // этот C + ещё один
            m = C;
          } else if (oliveBranch) {
            // Сразу после наказания — безусловное предложение мира.
            oliveBranch = false;
            m = C;
          } else if (oppLast === D) {
            if (rng() < GENEROSITY) {
              m = C; // великодушие: списываю на шум
            } else {
              m = D; // ровно один ответный удар…
              oliveBranch = true; // …и сразу рука мира
            }
          } else {
            m = C;
          }
        }
        intendedLast = m;
        return m;
      },
    };
  },
};
