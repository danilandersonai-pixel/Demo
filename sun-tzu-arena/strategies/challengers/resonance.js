/**
 * ДОСЬЕ · «Резонанс» (Resonance)
 *
 * Принцип трактата:
 *   «Тот, кто умеет заставить противника обнаружить форму, а сам формы не имеет,
 *    — сохраняет цельность». (VI. Полнота и пустота)
 *   Резонанс не приносит в бой заранее заготовленного характера. Он слушает,
 *   какой отклик даёт противник на каждое действие, и настраивается на его
 *   собственную частоту.
 *
 * Философия — как устроен предсказатель:
 *   Почти вся лига — конечные автоматы с короткой памятью: следующий ход
 *   противника есть функция одного-двух последних раундов. Резонанс строит
 *   таблицу «контекст → что он сделал дальше», где контекст — пара последних
 *   раундов обеих сторон (16 состояний, глубина 2), с откатом на контекст
 *   глубины 1 (4 состояния) и далее на априорное «он отвечает взаимностью».
 *   Формула отката: p2 = (c2 + W2·p1)/(n2 + W2), p1 = (c1 + W1·prior)/(n1 + W1).
 *   Так редкое наблюдение никогда не выдаётся за закономерность: пока данных
 *   мало, говорит априор, а не единственный случай. Все счётчики затухают с
 *   коэффициентом 0.98 за раунд — противник, сменивший поведение, перевешивает
 *   собственное прошлое примерно за полсотни раундов.
 *
 *   ЛОВУШКА И КАК ОНА ОБОЙДЕНА. Наивный «лучший ответ на предсказание» всегда
 *   даёт D: в одном раунде D доминирует при любой вероятности, и предсказатель
 *   вырождается в AlwaysDefect. Резонанс считает не раунд, а КУРС. Модель
 *   противника — марковская цепь на 16 состояниях; для каждого из четырёх
 *   курсов (всегда C, всегда D, зеркало, зеркало-после-двух) прогоняется точное
 *   распределение состояний на 40 шагов вперёд, включая собственный шум 5%, и
 *   считается средняя выплата за раунд. Выбирается курс с наибольшей
 *   установившейся ценностью, играется только его первый ход, а на следующем
 *   раунде расчёт повторяется по обновлённой модели. Против реагирующего
 *   противника курс «всегда D» сам себя наказывает внутри симуляции: он ведёт
 *   цепь в состояние взаимного предательства ценой 1.0 против 3.0 у взаимной
 *   верности, — поэтому вырождения не происходит.
 *
 *   МЕРА УВЕРЕННОСТИ. Отступление от сотрудничества требует запаса ценности:
 *   margin = 0.05 + 0.45·(1 − conf), где conf растёт с числом раундов и падает
 *   с энтропией текущего предсказания. Пока статистика тонка или прогноз
 *   размыт, D должно выигрывать с большим отрывом, иначе играется C: стабильные
 *   взаимные 3.0 — лучшее, что бывает в этой игре.
 *
 *   ЗОНД. «Заставить противника обнаружить форму»: пока не видно ни одного
 *   отклика на собственное предательство, а противник выглядит безответно
 *   добрым, Резонанс до шести раз с интервалом делает пробное D. Так
 *   безответный распознаётся за пару десятков раундов, а отвечающий закрывает
 *   вопрос первым же наказанием — зонды прекращаются, едва набрано шесть
 *   наблюдений отклика на D.
 *
 *   ОЛИВКОВАЯ ВЕТВЬ. Если стороны заперты во взаимном предательстве, модель
 *   сама из него не выйдет: она предсказывает D и отвечает D. Раз в 25 раундов
 *   Резонанс даёт два хода C подряд — проверку, не изменился ли противник.
 *   Против непреклонного агрессора это стоит около 0.1 очка за раунд, зато
 *   спасает пару зеркальных копий из ямы 1.0.
 *
 *   Случайность не используется вовсе: поведение полностью детерминировано
 *   историей матча.
 *
 * Сильные стороны:
 *   — распознаёт безответно доброго и доит его на ~4.7 за раунд;
 *   — не разрушает кооперацию с отвечающими: курс «всегда C» побеждает в
 *     расчёте, а шумовые срывы прощаются автоматически.
 *
 * Слабые стороны:
 *   — первые два-три десятка раундов уходят на разведку, против доверчивого
 *     это недобранные очки;
 *   — противник с памятью глубже двух раундов для модели невидим: он выглядит
 *     шумом, и Резонанс скатывается к осторожному сотрудничеству.
 *
 * Против кого рассчитана:
 *   Против автоматов с короткой памятью — зеркал, прагматиков, доверчивых и
 *   мстительных: их форма ложится в таблицу переходов целиком.
 */

var C = 'C';
var D = 'D';

var NOISE = 0.05; // предполагаемая вероятность искажения собственного хода
var HORIZON = 40; // горизонт оценки курса, раундов
var W0 = 2; // вес врождённого ожидания в общей оценке его добронравия
var W1 = 2; // вес отката «глубина 1 → общая оценка»
var W2 = 3; // вес отката «глубина 2 → глубина 1»
var BASE_TRUST = 0.6; // с чего начинается оценка его добронравия
var RECIPROCITY = 0.15; // поправка априора: после моего C — выше, после D — ниже
var PRIOR_FLOOR = 0.05;
var PRIOR_CEIL = 0.95;
var DECAY = 0.98; // затухание счётчиков за раунд
var CONF_ROUNDS = 20; // за сколько раундов уверенность выходит на единицу
var MARGIN_MIN = 0.05; // запас ценности для отступления при полной уверенности
var MARGIN_MAX = 0.45; // добавка к запасу при нулевой уверенности
var ENTROPY_PULL = 0.35; // насколько энтропия прогноза сбивает уверенность

var PROBE_MIN_LEN = 4; // раньше этого раунда не зондируем
var PROBE_CALM = 20; // до этого раунда зондируем редко: многие судят по первым
var PROBE_GAP_EARLY = 9; // интервал между зондами в осторожной фазе
var PROBE_GAP = 4; // интервал между зондами дальше
var PROBE_MAX = 10; // сколько зондов допустимо всего
var PROBE_TARGET = 8; // при стольких откликах на D зондирование прекращается
var PROBE_STOP_N = 2; // столько откликов достаточно, чтобы увидеть месть
var PROBE_STOP_P = 0.5; // доля C в откликах на D, ниже которой зонды бессмысленны
var PROBE_COOP = 0.85; // зондируем только выглядящего добрым

var GREED_COOP = 0.6; // кого считать «в основном верным» — его не предают без улик
var GREED_N = 3; // сколько наблюдений нужно, чтобы счесть его безответным
var GREED_P = 0.6; // и какая доля прощений среди них

var OLIVE_MIN_LEN = 24; // раньше этого раунда ветвь не предлагается
var OLIVE_GAP = 25; // интервал между оливковыми ветвями
var OLIVE_GAP_MAX = 120; // предел, до которого интервал растёт после отказов
var OLIVE_WINDOW = 12; // окно, по которому опознаётся яма взаимного D
var OLIVE_OPP_C = 2; // столько C противника в окне ещё считается ямой
var OLIVE_MY_D = 9; // столько моих D в окне — я тоже в яме

var POLICY_COUNT = 4; // всегда C, всегда D, зеркало, зеркало-после-двух
var STATES = 16;

/** Очки за раунд с точки зрения первого хода. */
function pay(a, b) {
  if (a === C) return b === C ? 3 : 0;
  return b === C ? 5 : 1;
}

/**
 * Индекс состояния: два последних раунда обеих сторон.
 * Биты: 3 — мой ход два раунда назад, 2 — его ход два раунда назад,
 *       1 — мой прошлый ход, 0 — его прошлый ход. Единица означает D.
 */
function stateIndex(m2, o2, m1, o1) {
  return (m2 === D ? 8 : 0) + (o2 === D ? 4 : 0) + (m1 === D ? 2 : 0) + (o1 === D ? 1 : 0);
}

/** Ход курса `policy` из состояния `s`. */
function policyMove(policy, s) {
  if (policy === 0) return C; // всегда C
  if (policy === 1) return D; // всегда D
  if (policy === 2) return s & 1 ? D : C; // зеркало: повторяю его прошлый ход
  return (s & 1) && (s & 4) ? D : C; // зеркало-после-двух: мщу за две подряд
}

/** Нормированная бинарная энтропия, 0..1. */
function entropy(p) {
  if (p <= 1e-9 || p >= 1 - 1e-9) return 0;
  return -(p * Math.log(p) + (1 - p) * Math.log(1 - p)) / Math.log(2);
}

