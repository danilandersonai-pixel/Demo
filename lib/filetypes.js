// Имена файлов, по которым сразу видно, что это тест.
var TEST_NAME = /(\.|_|-)(test|spec)\.[a-z0-9]+$/i;

/**
 * Описание файла для карточки в карте проекта.
 * Возвращает {title, text, icon, category}.
 */
function describeFile(relPath, isDir) {
  var rel = paths.toPosix(relPath || '');
  var name = paths.baseName(rel);
  var lower = name.toLowerCase();
  var ext = paths.extOf(rel);

  if (isDir) {
    return {
      title: 'Папка',
      text: describeDir(rel),
      icon: '📁',
      category: 'dir'
    };
  }

  if (TEST_NAME.test(name)) {
    return {
      title: 'Файл с тестами',
      text: 'Проверки для другого файла: запускают код и сверяют результат с ожидаемым. Если тут красное — что-то сломалось.',
      icon: '🧪',
      category: 'test'
    };
  }

  if (BY_NAME[lower]) {
    return {
      title: BY_NAME[lower][0],
      text: BY_NAME[lower][1],
      icon: iconFor(ext, lower),
      category: 'known'
    };
  }

  for (var i = 0; i < BY_DIR.length; i++) {
    if (BY_DIR[i][0].test(rel)) {
      var extra = BY_EXT[ext] ? ' ' + BY_EXT[ext][1] : '';
      return {
        title: BY_DIR[i][1],
        text: BY_DIR[i][2] + extra,
        icon: iconFor(ext, lower),
        category: 'bydir'
      };
    }
  }

  if (BY_EXT[ext]) {
    return {
      title: BY_EXT[ext][0],
      text: BY_EXT[ext][1],
      icon: iconFor(ext, lower),
      category: 'byext'
    };
  }

  return {
    title: ext ? 'Файл .' + ext : 'Файл без расширения',
    text: 'Тип не распознан. Посмотрите содержимое — если это текст, скорее всего, настройки или заметки.',
    icon: '📄',
    category: 'unknown'
  };
}

