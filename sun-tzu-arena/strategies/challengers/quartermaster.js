'use strict';

/**
 * ДОСЬЕ · «Интендант» (Quartermaster)
 *
 * Принцип трактата:
 *   «Кто не подсчитал заранее провиант и обоз — тот проиграет. Война любит
 *    победу и не любит продолжительности». (II. Ведение войны)
 *   Сунь-цзы во второй главе не рассуждает о доблести: он считает колесницы,
 *   волов и дневные расходы казны. Затяжная кампания разоряет даже победителя,
 *   поэтому полководец обязан знать цену каждому дню войны.
 *
 * Философия:
 *   Интендант не смотрит на последний ход противника — он смотрит в книги.
 *   История матча содержит оба хода каждого раунда, значит накопленные очки
 *   ОБЕИХ сторон восстанавливаются точно и за O(1) через счётчики совместных
 *   исходов:
 *       моё сальдо = 3·(C,C) + 0·(C,D) + 5·(D,C) + 1·(D,D)
 *       его сальдо = 3·(C,C) + 5·(C,D) + 0·(D,C) + 1·(D,D)
 *   Разность сводится к одной строке: diff = 5·((D,C) − (C,D)). Всё, что
 *   решает исход дуэли, — асимметричные раунды; взаимный мир и взаимная война
 *   на разрыв не влияют вовсе. Отсюда вся учётная политика:
 *
 *   1) Цена мира и цена войны. Раунд взаимного сотрудничества приносит 3.0,
 *      раунд взаимной войны — 1.0. Значит каждый день конфликта стоит ровно
 *      2 очка, и платят их обе стороны.
 *   2) Окупаемость удара. Удар по сотрудничающему даёт мне 5 вместо 3 (+2)
 *      и оставляет ему 0 вместо 3 (−3): сальдо смещается на 5 очков за раунд.
 *      Но если противник отвечает, следующий раунд стоит мне −2. Один удар по
 *      мстительному окупается только если война длится меньше одного раунда,
 *      то есть не окупается никогда. По тому, кто не отвечает, — чистые +2
 *      каждый раз. Поэтому Интендант тратит на РЕВИЗИЮ: раз в дюжину раундов,
 *      пока нет данных, он делает одну проверочную недопоставку и записывает,
 *      прислали ли рекламацию. Три наблюдения — и вердикт вынесен. Ревизия по
 *      отвечающему стоит около одного очка (5 сейчас, 0 при расплате), это
 *      дешевле, чем всю партию гадать.
 *   3) Потолок жадности. Против того, кто не мстит, Интендант не превращается
 *      в мародёра: он держит целевой отрыв около 1 очка на раунд. Отрыв ниже
 *      цели — берём поставку силой; отрыв набран — возвращаемся к взаимным 3.0,
 *      самой доходной статье бюджета. «Война любит победу и не любит
 *      продолжительности»: разрыв важнее максимума, а мир дешевле войны.
 *      Тот же порог работает и в обратную сторону — если противник обирает
 *      меня быстрее, чем я набираю отрыв, целевой уровень недостижим и режим
 *      сам вырождается в постоянную оборону.
 *   4) Тест на убыточность мира. Ожидаемая цена мира — 3·p(он C | я C);
 *      цена войны — 1 + 4·p(он C | я D). Когда война выигрывает заметно
 *      (с запасом сверх шума), объявляется осада. Разведку в осаде оплачивает
 *      сам шум: 5% моих ходов искажаются в C, давая бесплатные наблюдения
 *      «а не исправился ли он» — и учёт ведётся с затуханием, так что
 *      исправившийся противник возвращает мир без отдельных затрат.
 *   5) Мирная бухгалтерия долгов. Неспровоцированное предательство получает
 *      РОВНО один ответный удар. Но если его удар пришёл следом за моим
 *      (в том числе за искажённым шумом), счёт считается закрытым, и эхо не
 *      продолжается: обмен «5 и 0» против «0 и 5» балансирует сальдо ровно,
 *      а третий раунд войны — уже чистый убыток. Если у меня есть запас
 *      отрыва, часть чужих ошибок оплачивается из него без ответа.
 *
 * Сильные стороны:
 *   — решение принимается от накопленного сальдо, а не от последнего хода,
 *     поэтому одиночная помеха не сбивает курс и эхо-войны гасятся за два
 *     раунда: с собственной копией Интендант живёт почти на чистом мире;
 *   — ревизия отличает доверчивого от мстительного за три наблюдения и
 *     превращает первого в постоянную статью дохода, не срываясь в мародёрство;
 *   — экономический тест выводит из убыточного мира с непримиримыми (осада) и
 *     возвращает в мир, если противник исправился, — учёт с затуханием.
 *
 * Слабые стороны:
 *   — против «Зеркала» и его родни выиграть дуэль структурно нельзя: они не
 *     дают отыграть очки, потерянные на их собственных помехах, и Интендант
 *     сознательно не тратится на заведомо убыточную войну;
 *   — открывается доверием и потому дарит первому же чистому агрессору 5 очков
 *     форы, которые против него уже не вернуть;
 *   — ревизия — плановый убыток: против абсолютно мирного мстителя это
 *     несколько очков, отданных ради информации.
 *
 * Против кого рассчитана:
 *   Против доверчивых и слабо мстительных (доит их ровно до целевого отрыва) и
 *   против шумных сред, где остальные проедают бюджет на эхо-войнах. С
 *   надёжными партнёрами — и с собственной копией — держит мир, потому что
 *   считать умеет.
 */

var C = 'C';
var D = 'D';

// Матрица выплат — те же цифры, что в engine/payoff.js: книги должны сходиться.
var R = 3; // оба сотрудничают
var S = 0; // я сотрудничал, он предал
var T = 5; // я предал, он сотрудничал
var P = 1; // оба предали

// --- учётная политика ---
var AUDIT_STEP = 12; // не чаще одной ревизии в дюжину раундов
var AUDIT_UNTIL = 96; // позже ревизия уже не окупает оставшийся горизонт
var AUDIT_SAMPLES = 3; // столько наблюдений отклика нужно для вердикта
var NO_REVENGE_MIN = 0.75; // отклик C на мой D выше этого — он не мстит
var PARTNER_MIN = 0.7; // ниже этого отклика на мой C партнёр ненадёжен
var LEAD_TARGET = 1.05; // целевой отрыв, очков на раунд: потолок жадности
var FORGIVE_LEAD = 0.8; // с таким запасом чужую ошибку можно оплатить самому
var FORGIVE_CHANCE = 0.4; // и то не всегда: касса не бездонна
var WAR_MARGIN = 0.25; // война должна выигрывать заметно, а не в пределах шума
var PRIOR_WEIGHT = 1; // вес осторожного предположения при пустой выборке
var PRIOR_AFTER_D = 0.2; // без ревизии считаем, что противник мстит
var PRIOR_AFTER_C = 0.9; // и что на мир отвечают миром
var DECAY = 0.97; // старые записи списываются: важен нынешний контрагент

module.exports = {
  id: 'quartermaster',
  latin: 'Quartermaster',
  name: 'Интендант',
  color: '#fcd34d',
  glyph: '糧',
  family: 'challenger',
  tagline: 'Считает провиант, а не подвиги',
  dossier: {
    principle: '«Война любит победу и не любит продолжительности» — II. Ведение войны',
    philosophy:
      'Решает не последний ход, а сальдо матча: очки обеих сторон восстанавливаются из ' +
      'истории точно, и разрыв сводится к 5·((D,C) − (C,D)). Раунд мира стоит 3.0, раунд ' +
      'войны — 1.0, значит конфликт обходится в 2 очка за день обеим сторонам. Удар по ' +
      'мстительному не окупается никогда, по неотвечающему даёт чистые +2 — поэтому ' +
      'Интендант платит за ревизию, а набрав целевой отрыв около очка на раунд, ' +
      'возвращается к самой доходной статье: взаимным тройкам.',
    strengths: [
      'Решение от накопленного сальдо: помеха не сбивает курс, эхо гаснет за два раунда',
      'Ревизия за три наблюдения отделяет доверчивого от мстительного — и не жадничает сверх цели'
    ],
    weaknesses: [
      'Дуэль с «Зеркалом» и роднёй структурно не выигрывается — и он не тратится на неё',
      'Открывается доверием: чистому агрессору дарит 5 очков форы, которых уже не вернуть'
    ],
    targets: 'Против доверчивых и слабо мстительных, а также против шумных сред, где остальные проедают бюджет на эхо-войнах'
  },

  create: function (api) {
    var coin = api && typeof api.random === 'function' ? api.random : null;

    // --- книги учёта (состояние живёт в замыкании, один комплект на матч) ---
    var posted = 0; // сколько раундов уже проведено по книгам
    var sumAfterD = 0; // взвешенная сумма «он ответил C на мой D»
    var wAfterD = 0; // и её вес
    var nAfterD = 0; // сырое число наблюдений
    var sumAfterC = 0;
    var wAfterC = 0;
    var nAfterC = 0;
    var nextAudit = 10; // раунд, раньше которого ревизию не назначаем

    /** Провести в книги все ещё не учтённые раунды. Инкрементально, O(1) на раунд. */
    function post(h) {
      while (posted < h.length) {
        var i = posted;
        if (i >= 1) {
          var prev = h.mine(i - 1);
          var reply = h.opp(i) === C ? 1 : 0;
          if (prev === D) {
            sumAfterD = sumAfterD * DECAY + reply;
            wAfterD = wAfterD * DECAY + 1;
            nAfterD += 1;
          } else {
            sumAfterC = sumAfterC * DECAY + reply;
            wAfterC = wAfterC * DECAY + 1;
            nAfterC += 1;
          }
        }
        posted += 1;
      }
    }

    /** Оценка p(он C | я D). Пустая выборка — осторожное предположение о мести. */
    function replyToD() {
      return (sumAfterD + PRIOR_WEIGHT * PRIOR_AFTER_D) / (wAfterD + PRIOR_WEIGHT);
    }

    /** Оценка p(он C | я C) — сколько на самом деле стоит мой мир. */
    function replyToC() {
      return (sumAfterC + PRIOR_WEIGHT * PRIOR_AFTER_C) / (wAfterC + PRIOR_WEIGHT);
    }

    return {
      move: function (h) {
        var t = h.length;

        // Первый раунд: открытый кредит. Мир — самая доходная статья, и начинать
        // проверку его доступности дешевле всего с собственного взноса.
        if (t === 0) return C;

        post(h);

        // --- сальдо матча, восстановленное из истории точно ---
        var cc = h.count(C, C);
        var cd = h.count(C, D);
        var dc = h.count(D, C);
        var dd = h.count(D, D);
        var myScore = R * cc + S * cd + T * dc + P * dd;
        var hisScore = R * cc + T * cd + S * dc + P * dd;
        var lead = (myScore - hisScore) / t; // очков отрыва на раунд

        var pD = replyToD();
        var pC = replyToC();
        var audited = nAfterD >= AUDIT_SAMPLES;

        // --- 1. Вердикт «не мстит»: поставка силой до целевого отрыва ---
        // Удар стоит ему 3 очка, а мне приносит 2 — и ответа не будет.
        // Но отрыв важнее максимума: набрав цель, возвращаемся к тройкам.
        if (audited && pD >= NO_REVENGE_MIN && pC >= PARTNER_MIN) {
          return lead < LEAD_TARGET ? D : C;
        }

        // --- 2. Что дороже: мир или война ---
        // Цена мира 3·p(C|C) против цены войны 1 + 4·p(C|D). Запас WAR_MARGIN
        // не даёт объявить кампанию из-за случайных помех.
        if (nAfterC >= 4) {
          var peaceValue = R * pC;
          var warValue = P + (T - P) * (audited ? pD : PRIOR_AFTER_D);
          if (warValue > peaceValue + WAR_MARGIN) return D;
        }

        // --- 3. Ревизия: одна проверочная недопоставка, пока нет данных ---
        // Проводим только в спокойной книге (прошлый раунд — взаимный мир),
        // иначе отклик нельзя будет отнести именно на неё.
        if (
          !audited &&
          t >= nextAudit &&
          t <= AUDIT_UNTIL &&
          pC >= 0.78 &&
          h.opp(-1) === C &&
          h.mine(-1) === C
        ) {
          nextAudit = t + AUDIT_STEP;
          return D;
        }

        // --- 4. Мир с бухгалтерией долгов ---
        if (h.opp(-1) === C) return C; // поставки идут — платим тем же

        // Его удар пришёл следом за моим (в том числе за искажённым шумом):
        // сальдо уже выровнено обменом «5 и 0» против «0 и 5», третий раунд
        // войны — чистый убыток в 2 очка. Счёт закрыт.
        if (h.mine(-2) === D) return C;

        // Ответ уже нанесён — эхо не продлеваем.
        if (h.mine(-1) === D) return C;

        // Есть запас отрыва — часть чужих ошибок дешевле оплатить самому,
        // чем разменивать накопленное на войну.
        if (lead >= FORGIVE_LEAD && pC >= 0.85 && coin && coin() < FORGIVE_CHANCE) return C;

        // Неспровоцированное предательство: ровно один ответный удар.
        return D;
      }
    };
  }
};
