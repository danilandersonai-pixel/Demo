/**
 * Геометрия корпусов кораблей в нормированных координатах: нос смотрит вверх
 * (y < 0), единица — половина размера корабля. Рендер на Canvas умножает на
 * SHIP_SIZE мировых единиц, SVG-превью в магазине рисует в viewBox="-1.6 -1.6 3.2 3.2".
 */
import type { ShipShape } from './types';

export type Point = readonly [number, number];

export interface ShipGeometry {
  /** Внешний контур корпуса (замкнутый многоугольник). */
  hull: readonly Point[];
  /** Внутренний контур-деталь (кабина, рёбра) — рисуется тоньше. */
  inner: readonly Point[];
  /** Кольцо вокруг корпуса (щит-призрак), радиус в тех же единицах; 0 — нет. */
  ring: number;
  /** Сопла двигателей: отсюда летит выхлоп и шлейф. */
  engines: readonly Point[];
  /** Центр светящегося ядра. */
  core: Point;
}

