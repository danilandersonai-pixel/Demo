// ДОСЬЕ ────────────────────────────────────────────────────────────────
// «Прагматик» (Pavlov, win-stay / lose-shift) — классика.
// Принцип: сработало — повтори, не сработало — поменяй.
// Философия: без морали, только результат. Выплата T или R — «победа»,
// P или S — «поражение». Эквивалентно: оппонент кооперировал → повторяю
// свой ход; предал → меняю.
// Сильные стороны: чинит эхо-войны после шума (в отличие от «Зеркала»);
// возвращается к взаимной кооперации за пару раундов.
// Слабые стороны: против «Агрессора» глупо чередует C/D и доплачивает;
// доверчивых доит только через раз.
// Против кого рассчитан: против таких же адаптивных и против шума.
// ──────────────────────────────────────────────────────────────────────

import { C, D } from '../engine/game.js';

export default {
  id: 'pavlov',
  name: 'Прагматик',
  epithet: 'победил — повтори, проиграл — смени',
  color: '#ffb74d',
  dossier: {
    quote: 'Мне не нужна справедливость. Мне нужен результат.',
    principle: 'Win-stay / lose-shift: выплата T или R — повторить свой ход, P или S — сменить.',
    strengths: ['Самовосстановление после шума: эхо-война гаснет за 1–2 раунда', 'Наказывает и прощает, не зная слов «месть» и «прощение»'],
    weaknesses: ['Против вечного агрессора наивно чередует C/D (0.5 вместо 1.0)', 'Читается опытным моделистом и эксплуатируется'],
    targets: 'Против шумной среды и адаптивных соседей; страховка от эхо-войн.',
  },
  create() {
    return {
      move(mine, theirs) {
        if (mine.length === 0) return C;
        const myLast = mine[mine.length - 1];
        const oppLast = theirs[theirs.length - 1];
        // Оппонент кооперировал → выплата T или R («победа») → повторяю ход.
        // Оппонент предал → выплата P или S («поражение») → меняю ход.
        if (oppLast === C) return myLast;
        return myLast === C ? D : C;
      },
    };
  },
};
