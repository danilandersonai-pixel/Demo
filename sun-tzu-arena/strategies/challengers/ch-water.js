// ============================================================================
// «Вода» — стратегия-претендент для «Арены Сунь-Цзы».
// Образ: глава VI трактата («Пустота и полнота»): «У войска нет постоянной
// мощи, у воды нет постоянной формы. Кто умеет, следуя врагу, менять форму, —
// тот божественен».
//
// ПРИНЦИП. Вода прощупывает природу оппонента и перетекает между формами
// одной сущности:
//
//  • ПОТОК (по умолчанию) — покаянное великодушное зеркало. Сотрудничает;
//    на незаслуженное предательство отвечает ударом, но с шансом 12% прощает.
//    Ключ к шуму 5%: любой СВОЙ фактический D (в том числе случайный,
//    искажённый шумом) выдаёт оппоненту «лицензию» на два ответных удара —
//    их вода принимает молча, не отвечая. Это гасит эхо-войны в селф-матчах
//    и не даёт заклиниться с двухударными карателями (осада «Полководца»).
//    Лицензия быстро истекает и не действует во время явной атаки.
//    Пока природа врага не ясна, вода изредка «щупает дно» одиночным D,
//    заранее готовая принять наказание; как только зеркальная природа
//    доказана — пробы прекращаются.
//
//  • КАМЕНЬ — если оппонент обрушивает лавину предательств (~75% D в недавнем
//    окне), вода замерзает: почти сплошной D с редкой (6%) оливковой ветвью;
//    оттаивает, как только противник снова начинает сотрудничать.
//
//  • ЛЁД — если накоплены свидетельства, что оппонент бьёт БЕЗ ПОВОДА
//    (доля его D после моих фактических C ≥ 30% при солидной выборке) и
//    продолжает предавать — значит, его ходы не зависят от моих (хаос,
//    триггернутый мститель, наглый эксплуататор). Вода промерзает надолго:
//    почти сплошной D; оттаивает только при устойчивом возврате оппонента
//    к сотрудничеству.
//
//  • ПРИЛИВ — если свидетельства показали, что оппонент не отвечает на удары
//    (доля возмездий ≤ 20% при почти полном сотрудничестве), вода заполняет
//    пустоту: мягкая эксплуатация (D ~60%) с мгновенным откатом к
//    сотрудничеству и умиротворением при первых признаках возмездия; после
//    отката порог повторного входа ужесточается.
//
// ─── КРУГ 2 — что изменено и почему (по логам круга 1, под основную лигу) ───
//  1. Новая форма «ЛЁД»: статистика «ударов без повода» (D оппонента в ответ
//     на мой фактический C) вскрывает противников, глухих к моим ходам, —
//     Хаос, триггернутых мстителей, наглых эксплуататоров. Против них
//     единственно верная форма — почти сплошной D. «Камень» их не держал:
//     случайные ~50% C оппонента постоянно «оттаивали» осаду.
//  2. Лицензия на прощение не действует во время явной атаки (≥5 D оппонента
//     в последних 8 ходах): против вечного агрессора вода раньше смыкается
//     в оборону — меньше подставленных щёк в первых раундах.
//  3. Пробы прекращаются, как только зеркальная природа врага доказана
//     (≥3 события, доля возмездий ≥ 50%): в круге 1 лишние пробы дарили очки
//     Полководцу (2.82 против его 2.98), Зеркалу и собственной копии.
//  4. «Прилив» наступает раньше (с ~30-го раунда, пробы чаще — пауза 10
//     вместо 15) и давит плотнее (D 55% → 60%): в основной лиге есть
//     безответные жертвы, их надо доить быстрее.
//  5. Распознавание «двухударной» сигнатуры: если мой одиночный D дважды
//     наказан парой D подряд — передо мной каратель типа осады Полководца.
//     С этого момента одиночные D (его шум) прощаю полностью и караю только
//     серии 2+: возмездие одиночке запускало дорогой цикл «удар — двойная
//     кара — поглощение». Одиночных эксплуататоров при этом ловит «Лёд»
//     по статистике ударов без повода.
//
// СИЛЬНЫЕ СТОРОНЫ: устойчивость к шуму (лицензии + великодушие); стабильные
// селф-матчи (почти чистое взаимное C); не проваливается против вечных
// предателей; замораживает хаос; добирает очки с безответных альтруистов;
// мирно живёт со всеми тремя фазами «Полководца».
// СЛАБЫЕ СТОРОНЫ: первые раунды против агрессора уступает чистым хищникам —
// вода сначала пробует мир; рваные стратегии со средней долей предательств
// вскрываются лишь со временем, пока копится статистика ударов без повода.
// ПРОТИВ КОГО: зеркальные и великодушные стратегии (чемпион во всех фазах),
// собственные копии, вечные предатели, хаотичные и триггерные агрессоры,
// безответные кооператоры.
// ============================================================================

export default {
  id: 'ch-water',
  name: 'Вода',
  epithet: 'Принимает форму врага',
  color: '#54c8e8',
  dossier: {
    quote: 'У воды нет постоянной формы: она избегает полного и заполняет пустое. Кто побеждает, меняясь вслед за врагом, — тот божественен.',
    principle: 'Покаянное великодушное зеркало, перетекающее между формами: поток (сотрудничество с лицензией на прощение), камень (осада против лавины предательств), лёд (глухая оборона против бьющих без повода) и прилив (мягкая эксплуатация безответного).',
    strengths: [
      'Гасит эхо-войны от шума: свой фактический D выдаёт врагу лицензию на два безнаказанных ответных удара',
      'Стабильные селф-матчи и мир с зеркальными, великодушными и двухударно-карающими стратегиями',
      'Не тонет против вечного предателя (камень), замораживает хаос и триггернутых мстителей (лёд), доит безответного альтруиста (прилив)',
    ],
    weaknesses: [
      'Первые раунды против агрессора уступает чистым хищникам — вода сначала пробует мир',
      'Рваные стратегии со средней долей предательств вскрываются лишь со временем, пока копится статистика «ударов без повода»',
    ],
    targets: 'Чемпион-«Полководец» во всех трёх фазах, собственные копии, вечные предатели, хаотичные и триггерные агрессоры, безответные кооператоры.',
    round2:
      'Добавлена форма «Лёд»: по доле ударов без повода (D оппонента после моего C ≥ 30% при выборке ≥ 30) распознаю противников, глухих к моим ходам — Хаос, триггернутых мстителей, — и промерзаю в D, пока они устойчиво не исправятся; «камень» их не держал из-за случайных оттепелей. Лицензия на прощение отключена во время явной атаки (≥5 D в последних 8 ходах) — быстрее оборона от вечного агрессора. Пробы прекращаются после доказательства зеркальной природы (≥3 событий, возмездие ≥ 50%) — в круге 1 они дарили очки Полководцу и селф-копии. «Прилив» наступает раньше (~30-й раунд) и давит плотнее (D 60%) — в основной лиге безответных жертв надо доить быстрее. Распознав «двухударную» сигнатуру карателя (мой одиночный D дважды наказан парой D), прощаю его одиночные шумовые D полностью и караю только серии — возмездие одиночке против осады запускало дорогой цикл двойной кары.',
  },
  create(rng) {
    // --- Состояние ---
    let excuse = 0;            // сколько чужих D я готов счесть заслуженными
    let lastMyDRound = -10;    // раунд моего последнего фактического D
    let myDefEvents = 0;       // мои фактические D как «стимулы» (n-2)
    let oppRetals = 0;         // ответные D оппонента на мои D
    let myCoopStim = 0;        // мои фактические C как «стимулы» (n-2)
    let oppUnprov = 0;         // D оппонента после моего C — «удары без повода»
    let oppCoops = 0;          // всего C оппонента
    let stone = false;         // форма «камень»
    let ice = false;           // форма «лёд»
    let tide = false;          // форма «прилив»
    let minEventsForTide = 5;  // порог свидетельств для входа в прилив
    let ratioCapForTide = 0.2; // порог доли возмездий для входа в прилив
    let appease = 0;           // раунды безусловного умиротворения
    let lastProbeRound = -100; // раунд последней разведки боем
    let doubleHits = 0;        // мои одиночные D, наказанные парой D подряд
    let siegeAware = false;    // враг — двухударный каратель: одиночные D прощаем

    function countDTail(arr, k) {
      const from = Math.max(0, arr.length - k);
      let d = 0;
      for (let i = from; i < arr.length; i++) {
        if (arr[i] === 'D') d++;
      }
      return d;
    }

    return {
      move(mine, theirs) {
        const n = mine.length;
        if (n === 0) return 'C';

        const prevMy = mine[n - 1];
        const prevOpp = theirs[n - 1];

        // --- Свидетельства о природе оппонента ---
        if (prevOpp === 'C') oppCoops++;
        // Ход оппонента в раунде n-1 — ответ на мой ход в раунде n-2.
        if (n >= 2) {
          if (mine[n - 2] === 'D') {
            myDefEvents++;
            if (prevOpp === 'D') oppRetals++;
          } else {
            myCoopStim++;
            if (prevOpp === 'D') oppUnprov++;
          }
        }
        // «Двухударная» сигнатура: мой одиночный D в раунде n-3 наказан
        // парой D оппонента в раундах n-2 и n-1.
        if (
          !siegeAware &&
          n >= 3 &&
          mine[n - 3] === 'D' &&
          (n === 3 || mine[n - 4] === 'C') &&
          theirs[n - 2] === 'D' &&
          theirs[n - 1] === 'D'
        ) {
          doubleHits++;
          if (doubleHits >= 2) siegeAware = true;
        }

        // --- Лицензия на прощение: мой фактический D разрешает врагу
        //     до двух ответных ударов; лицензия быстро истекает ---
        if (prevMy === 'D') {
          lastMyDRound = n - 1;
          excuse = 2;
        } else if (n - 1 - lastMyDRound > 3) {
          excuse = 0;
        }

        // Круг 2: во время явной атаки (≥5 D в последних 8) лицензия не действует.
        const underAssault = countDTail(theirs, 8) >= 5;
        let oppDExcused = false;
        if (prevOpp === 'D' && excuse > 0 && !underAssault) {
          excuse--;
          oppDExcused = true;
        }

        const oppCoopRate = oppCoops / n;
        const retalRatio = myDefEvents > 0 ? oppRetals / myDefEvents : 1;
        const unprovRate = myCoopStim > 0 ? oppUnprov / myCoopStim : 0;

        // --- Форма «ЛЁД» (круг 2): глухая оборона против бьющих без повода ---
        if (!ice && myCoopStim >= 30 && unprovRate >= 0.3 && countDTail(theirs, 20) >= 6) {
          ice = true;
          stone = false;
          tide = false;
        }
        if (ice) {
          if (n >= 20 && countDTail(theirs, 20) <= 3) {
            ice = false;                      // устойчиво исправился — оттаиваем
            if (excuse < 1) excuse = 1;
          } else {
            return rng() < 0.05 ? 'C' : 'D';
          }
        }

        // --- Форма «КАМЕНЬ»: осада против лавины предательств ---
        const w = Math.min(n, 12);
        if (!stone && n >= 8 && countDTail(theirs, 12) >= Math.ceil(0.75 * w)) {
          stone = true;
          tide = false;
        }
        if (stone) {
          const thawC = Math.min(n, 10) - countDTail(theirs, 10);
          if (thawC >= 5) {
            stone = false;                    // противник оттаял — вода течёт снова
            if (excuse < 1) excuse = 1;       // амнистия на выходе
          } else {
            return rng() < 0.06 ? 'C' : 'D';  // редкая оливковая ветвь
          }
        }

        // --- Форма «ПРИЛИВ»: мягкая эксплуатация безответного ---
        if (tide) {
          if (retalRatio > 0.25 || countDTail(theirs, 10) >= 3) {
            tide = false;                     // враг очнулся — отлив и умиротворение
            minEventsForTide = myDefEvents + 6;
            ratioCapForTide = 0.12;
            appease = 3;
            excuse = 2;
          }
        } else if (
          n >= 30 &&
          myDefEvents >= minEventsForTide &&
          retalRatio <= ratioCapForTide &&
          oppCoopRate >= 0.85
        ) {
          tide = true;
        }
        if (tide) {
          if (prevOpp === 'D') return 'C';    // успокоить и присмотреться
          return rng() < 0.6 ? 'D' : 'C';
        }

        // --- Форма «ПОТОК»: покаянное великодушное зеркало ---
        if (appease > 0) {
          appease--;
          return 'C';
        }

        if (prevOpp === 'D' && !oppDExcused) {
          // Против двухударного карателя одиночные D (его шум) прощаем
          // полностью — караем только серии 2+ (одиночек ловит «Лёд»).
          if (siegeAware && (n < 2 || theirs[n - 2] === 'C')) {
            return 'C';
          }
          return rng() < 0.88 ? 'D' : 'C';    // возмездие с великодушием 12%
        }

        // Разведка боем: пока свидетельств мало, изредка щупаем дно одиночным D.
        // Круг 2: если зеркальная природа уже доказана — больше не пробуем.
        const natureClear = myDefEvents >= 3 && retalRatio >= 0.5;
        if (
          n >= 12 &&
          !natureClear &&
          myDefEvents < 5 &&
          oppCoopRate >= 0.85 &&
          prevOpp === 'C' &&
          excuse === 0 &&
          n - lastProbeRound >= 10 &&
          rng() < 0.12
        ) {
          lastProbeRound = n;
          excuse = 2;                         // заранее готов принять наказание
          return 'D';
        }

        return 'C';
      },
    };
  },
};
