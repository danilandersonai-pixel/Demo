// ============================================================================
// «Поджигатель» — претендент по мотивам главы XII трактата («Огневое нападение»)
// ----------------------------------------------------------------------------
// ПРИНЦИП. «Огонь пускают, когда время сухое и ветер попутный». База — смиренный
// кооператор: сотрудничает, за случайный (шумовой) удар по мирному противнику
// накладывает на себя епитимью и молча принимает до двух ответных ударов, чтобы
// не раздувать эхо-войны. Поверх базы — механика поджога: стратегия постоянно
// измеряет, НАКАЗЫВАЮТСЯ ли её фактические D (шумовые, разведывательные, боевые).
// Если одиночные удары систематически сходят с рук — это подозрение на «сухую
// траву»; правду вскрывает контрольный дуплет (два D подряд), и лишь после него
// начинается настоящий пожар — до сплошного огня по безответной жертве.
// Отпор — мгновенный отбой, извинение и долгий запрет на огонь.
//
// ФИЛОСОФИЯ. Предавать не «когда хочется», а когда обстоятельства открылись:
// безответная жертва (эксплуатация безнаказанна), уже идущая война (оборона,
// изредка оливковая ветвь), выгодное окно великодушия (одиночные удары, которые
// противник прощает). Против «мстителей», карающих сериями (два удара за один),
// включается терпение: одиночные чужие D прощаются полностью — воевать с осадой
// дороже, чем стерпеть шум.
//
// ----------------------------------------------------------------------------
// КРУГ 2 — что изменено и почему (по логам круга 1: лучший бомбардир поля,
// но 2-е место в эволюции — победителя сделала диагональ: его селф-матч лучше).
//
// 1. АДАПТИВНОЕ ВЕЛИКОДУШИЕ. Прощение одиночного чужого D больше не 15%, а
//    лестница по доле его D в окне 20 раундов: 80% / 50% / 30% / 12%. В
//    селф-матче чужие одиночные D — почти всегда шум, и прощение стоит паре
//    1 очко вместо 2 за ответный удар: диагональ растёт (селф-матч поднялся
//    с ~2.78 до ~2.88 при потолке шума ~2.95). Хищникам скидка исчезает сама.
// 2. КОНТРОЛЬНЫЙ ДУПЛЕТ — ОГОНЬ НЕ ЖЖЁТ РОДНЮ. Диагноз круга 1: великодушный
//    близнец неотличим от доормата по одиночным ударам, и поджоги против
//    самого себя съедали диагональ. По одиночным ударам теперь только
//    ПОДОЗРЕНИЕ (>=5 замеров в живом окне, наказаний <=15%); розжиг требует
//    контрольного дуплета — двух D подряд. Близнец и любой великодушный
//    каратель бьют по сериям всегда (~96% обнаружения), доормат — никогда.
//    Дуплет наказан — кулдаун 40, а после двух проваленных тестов огонь
//    запрещён навсегда. Пройден — сразу плотный огонь (через раунд, при
//    безнаказанности — сплошной).
// 3. Страховки огня: аудит прибыльности (через 12+ раундов пожар обязан
//    приносить больше доогневого фона — иначе отбой), наблюдения выцветают
//    за 80 раундов (противник мог сменить фазу), против «мстителя» (карает
//    сериями, как осада Полководца) огонь не разводится вовсе.
// 4. ВОЕННОЕ ПОЛОЖЕНИЕ ПРОТИВ ХРОНИКОВ. Помимо порога 55% в окне 15 раундов,
//    война объявляется и при 40%+ в окне 40 — но только если противник НЕ
//    зеркалит меня (эхо-детектор: доля его ходов, повторяющих мой предыдущий,
//    < 65%). Против случайного «Хаоса» и вялотекущих агрессоров постоянное D
//    приносит ~2.9 вместо размена, а зеркала под клаузу не попадают.
// ============================================================================

export default {
  id: 'ch-fire',
  name: 'Поджигатель',
  epithet: 'Огонь по сухой траве',
  color: '#ff6b35',
  dossier: {
    quote: 'Огонь пускают, когда время сухое и ветер попутный: нападай не когда хочешь, а когда обстоятельства открылись.',
    principle: 'Смиренный кооператор с епитимьёй за случайные удары и адаптивным великодушием; безответность одиночных D — лишь подозрение, розжиг только после безнаказанного контрольного дуплета (D,D): близнец и каратели бьют по сериям, доормат — никогда.',
    strengths: [
      'Диагональ: великодушие до 80% на мирном фоне гасит шумовые эхо, а контрольный дуплет не даёт огню жечь родню — селф-матч у потолка шума',
      'Дожимает безответных плотным огнём, а против хроников-агрессоров и рандома уходит в выгодную глухую оборону',
    ],
    weaknesses: [
      'Дуплеты и разведывательные поджоги дарят пару очков строгим зеркалам; великодушных карателей больше не доит одиночными',
      'Два проваленных дуплета запрещают огонь навсегда — ложные срабатывания от шума оставляют эксплуатацию недожатой',
    ],
    targets: 'Против доорматов и всепрощающих — эксплуатация после дуплет-теста; с зеркалами и карателями — мир; против вечных и случайных предателей — оборона.',
    round2: 'Круг 1: лучший бомбардир (2.948), но 2-е место в эволюции — решала диагональ (селф-матч). Изменения: (1) адаптивное великодушие 80/50/30/12% по доле чужих D в окне 20 — шум в селф-матче прощается почти даром, хищники скидку теряют; (2) контрольный дуплет: одиночная безответность — лишь подозрение, огонь только после двух безнаказанных D подряд — близнец и великодушные каратели бьют по сериям всегда, доормат никогда, поэтому огонь больше не жжёт родню; страховки — аудит прибыльности, выцветание наблюдений за 80 раундов, лимит 2 теста, запрет при «мстителе»; (3) военное положение против хроников (40%+ в окне 40) с эхо-детектором, чтобы не воевать с зеркалами — Хаос и вялые агрессоры встречают сплошное D (~2.9 против рандома).',
  },
  create(rng) {
    var lastIntended = null;   // мой задуманный ход прошлого раунда
    var penanceLeft = 0;       // сколько ответных ударов приму молча
    var penanceUntil = -1;     // индекс раунда, до которого действует епитимья
    var probeWindow = [];      // исходы моих фактических D: {p: наказан?, r: раунд}
    var unpunishedStreak = 0;  // подряд ненаказанных моих D
    var fireActive = false;    // идёт ли поджог
    var fireGap = 2;           // сколько мирных раундов между поджогами
    var sinceMyD = 99;         // раундов с моего последнего фактического D
    var fireCooldownUntil = -1;// до какого раунда огонь запрещён после отпора
    var fireRetreats = 0;      // сколько раз огонь гасили (2 = запрет навсегда)
    var ignitionRound = -1;    // раунд розжига текущего пожара
    var fireBaseline = 0;      // мой средний доход за 20 раундов до розжига
    var scoutsLeft = 3;        // лимит разведывательных поджогов
    var avenger = false;       // противник карает сериями (2 удара за 1)
    var confirmTestsLeft = 2;  // лимит контрольных «дуплетов» (D,D) перед розжигом
    var confirmRound = -1;     // раунд первого ствола дуплета (-1 = теста нет)
    var confirmStage = 0;      // 0 нет, 1 дан первый ствол, 2 дан второй

    function tally(arr) {
      var k = 0;
      for (var i = 0; i < arr.length; i++) if (arr[i].p) k++;
      return k;
    }

    function dRate(arr, win) {
      var m = Math.min(win, arr.length);
      if (m === 0) return 0;
      var k = 0;
      for (var i = arr.length - m; i < arr.length; i++) if (arr[i] === 'D') k++;
      return k / m;
    }

    function segAvg(mine, theirs, from) {
      var s = 0;
      var c = 0;
      for (var i = from; i < mine.length; i++) {
        if (mine[i] === 'C') s += theirs[i] === 'C' ? 3 : 0;
        else s += theirs[i] === 'C' ? 5 : 1;
        c++;
      }
      return c > 0 ? s / c : 0;
    }

    // Доля раундов, где их ход повторил мой предыдущий: эхо-детектор зеркал.
    function mirrorRate(mine, theirs) {
      var n = mine.length;
      var m = Math.min(30, n - 1);
      if (m <= 0) return 0;
      var k = 0;
      for (var i = n - 1 - m; i < n - 1; i++) {
        if (theirs[i + 1] === mine[i]) k++;
      }
      return k / m;
    }

    return {
      move: function (mine, theirs) {
        var n = mine.length;
        if (n === 0) {
          lastIntended = 'C';
          return 'C';
        }

        var myPrev = mine[n - 1];
        var oppPrev = theirs[n - 1];

        // --- учёт прошлого раунда -------------------------------------------
        if (myPrev === 'D') sinceMyD = 0; else sinceMyD++;

        // Мой прошлый фактический D был «несправедливым» (шум на мирном фоне):
        // епитимья — приму до двух ответных ударов, не отвечая.
        if (myPrev === 'D' && lastIntended === 'C' && (n < 2 || theirs[n - 2] === 'C')) {
          penanceLeft = 2;
          penanceUntil = n + 3;
        }

        // Ответ противника на мой D двухраундовой давности: наказан ли поджог?
        if (n >= 2 && mine[n - 2] === 'D') {
          var punished = oppPrev === 'D';
          probeWindow.push({ p: punished, r: n });
          if (probeWindow.length > 12) probeWindow.shift();
          if (punished) unpunishedStreak = 0; else unpunishedStreak++;
        }
        // Старые наблюдения выцветают: противник мог сменить фазу.
        while (probeWindow.length > 0 && probeWindow[0].r < n - 80) probeWindow.shift();

        // --- разбор контрольного дуплета ------------------------------------
        if (confirmStage >= 1) {
          if (confirmStage === 1 && n > confirmRound + 1) {
            // Второй ствол не вышел (вмешался их D) — тест не состоялся.
            confirmTestsLeft++;
            confirmStage = 0;
            confirmRound = -1;
            fireCooldownUntil = Math.max(fireCooldownUntil, n + 8);
          } else if (mine[confirmRound] !== 'D' ||
              (confirmStage === 2 && mine[confirmRound + 1] !== 'D')) {
            // Шум сорвал дуплет — тест не состоялся, попытку возвращаем.
            confirmTestsLeft++;
            confirmStage = 0;
            confirmRound = -1;
            fireCooldownUntil = Math.max(fireCooldownUntil, n + 8);
          } else {
            var teeth = false;
            var upTo = Math.min(confirmRound + 2, n - 1);
            for (var t = confirmRound + 1; t <= upTo; t++) {
              if (theirs[t] === 'D') teeth = true;
            }
            if (teeth) {
              // У противника есть зубы: дуплет наказан — огня здесь не будет.
              confirmStage = 0;
              confirmRound = -1;
              fireCooldownUntil = n + 40;
              if (confirmTestsLeft <= 0) fireRetreats = 2; // навсегда
            } else if (confirmStage === 2 && n >= confirmRound + 3) {
              // Дуплет прошёл безнаказанно: трава сухая — поджигаем всерьёз.
              confirmStage = 0;
              confirmRound = -1;
              fireActive = true;
              fireGap = 1;
              ignitionRound = n;
              fireBaseline = segAvg(mine, theirs, Math.max(0, n - 20));
            }
          }
        }

        // Мститель: мой одиночный D (на мирном фоне) наказан серией из двух.
        if (!avenger && n >= 3 &&
            mine[n - 3] === 'D' && theirs[n - 3] === 'C' &&
            mine[n - 2] === 'C' && theirs[n - 2] === 'D' &&
            mine[n - 1] === 'C' && theirs[n - 1] === 'D') {
          avenger = true;
        }

        // --- отбой пожара ----------------------------------------------------
        if (fireActive) {
          var L = probeWindow.length;
          var lastFour = 0;
          for (var q = Math.max(0, L - 4); q < L; q++) if (probeWindow[q].p) lastFour++;
          var lastSix = 0;
          for (var w = Math.max(0, L - 6); w < L; w++) if (probeWindow[w].p) lastSix++;
          var twoInARow = fireGap >= 1 && L >= 2 && probeWindow[L - 1].p && probeWindow[L - 2].p;
          var threeOfFour = fireGap === 0 && L >= 4 && lastFour >= 3;
          var halfBurnt = L >= 6 && lastSix >= 3;
          var audited = n - ignitionRound >= 12 &&
            segAvg(mine, theirs, Math.max(ignitionRound, n - 15)) < fireBaseline + 0.2;
          if (twoInARow || threeOfFour || halfBurnt || avenger || audited) {
            // Отпор или пожар не окупается: гасим, каемся, долгий запрет.
            fireActive = false;
            fireGap = 2;
            fireRetreats++;
            fireCooldownUntil = n + (audited ? 50 : 40);
            probeWindow = [];
            unpunishedStreak = 0;
            penanceLeft = 2;
            penanceUntil = n + 3;
          }
        }

        // --- военное положение ----------------------------------------------
        var def15 = dRate(theirs, 15);
        var atWar = (n >= 12 && def15 >= 0.55) ||
          (n >= 20 && def15 >= 0.3 && dRate(theirs, 40) >= 0.4 &&
           mirrorRate(mine, theirs) < 0.65);
        if (atWar) {
          if (rng() < 0.06) { // редкая оливковая ветвь против взаимного тупика
            lastIntended = 'C';
            return 'C';
          }
          lastIntended = 'D';
          return 'D';
        }

        // --- их последний ход — D -------------------------------------------
        if (oppPrev === 'D') {
          if (penanceLeft > 0 && n <= penanceUntil) {
            penanceLeft--;
            lastIntended = 'C';
            return 'C';
          }
          var streak2 = n >= 2 && theirs[n - 2] === 'D';
          if (!streak2) {
            // Одиночный D: против мстителя — полное терпение, иначе адаптивное
            // великодушие — лестница по доле их D в окне 20: чем мирнее фон,
            // тем щедрее прощение (шум прощается почти всегда).
            var d20 = dRate(theirs, 20);
            var mercy = d20 <= 0.1 ? 0.8 : d20 <= 0.16 ? 0.5 : d20 <= 0.24 ? 0.3 : 0.12;
            if (avenger || rng() < mercy) {
              lastIntended = 'C';
              return 'C';
            }
            lastIntended = 'D';
            return 'D';
          }
          // Серия 2+: отвечаю; мстителю — один удар и готовность стерпеть ответ.
          if (avenger) {
            penanceLeft = 2;
            penanceUntil = n + 4;
          }
          lastIntended = 'D';
          return 'D';
        }

        // --- их последний ход — C: мир, разведка или поджог -----------------
        if (confirmStage === 1 && n === confirmRound + 1) {
          // Второй ствол контрольного дуплета.
          confirmStage = 2;
          penanceLeft = 2;
          penanceUntil = n + 4;
          lastIntended = 'D';
          return 'D';
        }

        if (!fireActive && confirmStage === 0 && !avenger && fireRetreats < 2 &&
            n > fireCooldownUntil && n >= 18) {
          var Lw = probeWindow.length;
          if (Lw >= 5 && tally(probeWindow) / Lw <= 0.15 && unpunishedStreak >= 2 &&
              confirmTestsLeft > 0) {
            // Одиночные удары сходят с рук — проверяем дуплетом: близнец и
            // великодушные каратели бьют по сериям всегда, доормат — никогда.
            confirmTestsLeft--;
            confirmRound = n;
            confirmStage = 1;
            penanceLeft = 2;
            penanceUntil = n + 5;
            lastIntended = 'D';
            return 'D';
          }
          if (Lw < 5 && scoutsLeft > 0 && sinceMyD >= 6 && rng() < 0.25) {
            // Разведывательный поджог: узнать, наказывают ли здесь вообще.
            scoutsLeft--;
            penanceLeft = 2;
            penanceUntil = n + 4;
            lastIntended = 'D';
            return 'D';
          }
        }

        if (fireActive) {
          if (unpunishedStreak >= 8) fireGap = 0;       // сплошной огонь
          if (sinceMyD >= fireGap) {
            penanceLeft = 2;                            // если накажут — приму
            penanceUntil = n + 4;
            lastIntended = 'D';
            return 'D';
          }
        }

        lastIntended = 'C';
        return 'C';
      },
    };
  },
};
